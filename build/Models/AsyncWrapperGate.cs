#nullable enable

using System;

/// <summary>
/// The policy for what a FAILED async-wrapper build means to the leg that requested it.
///
/// <para><b>The defect this closes.</b> <c>RunBuildAsyncWrapper</c> has always returned a
/// success flag, but four of its five callers — the iOS/device, macOS, Mac Catalyst and tvOS
/// runtime-test legs — threw the value away and carried on, on the theory that "the downstream
/// tests will surface the failure anyway". They surface *a* failure, not *the* failure. A Mac
/// Catalyst leg soft-failed its wrapper build, ran the app against the stale wrapper from the
/// previous build, and reported <c>121 passed / 1296 failed, Done: False</c>. Every one of those
/// 1296 failures was noise generated by a single missing artifact; re-running once the wrapper
/// compiled gave <c>2587 / 0 / 37</c>. A build failure must be reported as a build failure.</para>
///
/// <para><b>The policy.</b> Hard-fail by default; <c>--permissive</c> demotes it to a warning and
/// proceeds. That is exactly how <c>--permissive</c> already behaves for the compile gate's other
/// fail-closed steps, and it is deliberately NOT "warn by default" — warning by default is what
/// the harness effectively did before, and that behaviour is the bug.</para>
/// </summary>
public static class AsyncWrapperGate
{
    /// <summary>
    /// Whether a wrapper-build outcome must abort the leg. Fail-closed: only an explicit
    /// <paramref name="permissive"/> opt-out downgrades a failure to a warning.
    /// </summary>
    public static bool ShouldFail(bool wrapperOk, bool permissive) => !wrapperOk && !permissive;

    /// <summary>
    /// Whether a wrapper-build outcome should be reported as a warning and execution continued.
    /// Only ever true under <c>--permissive</c>; a successful build reports nothing.
    /// </summary>
    public static bool ShouldWarn(bool wrapperOk, bool permissive) => !wrapperOk && permissive;

    /// <summary>
    /// The diagnosis a reader gets instead of a wall of unexplained test failures. Names the leg,
    /// says what failed, says what the consequence would have been, and names the opt-out.
    /// </summary>
    public static string FailureMessage(string legLabel) =>
        $"Async wrapper build FAILED for {legLabel}. This is a build failure, not a test result: the " +
        "single-shot compile of the post-processed Swift wrapper did not succeed (the generator's own " +
        "SwiftWrapperPostProcessor already scrubbed it, so there is no strip-and-retry fallback). " +
        "Continuing would run the tests against a stale or absent wrapper and report the missing " +
        "entry points as hundreds of unrelated test failures. Fix the wrapper compile; pass " +
        "--permissive to downgrade this to a warning and proceed anyway.";

    /// <summary>The same diagnosis, worded for the <c>--permissive</c> path that proceeds regardless.</summary>
    public static string WarningMessage(string legLabel) =>
        $"Async wrapper build FAILED for {legLabel}; continuing because --permissive was passed. " +
        "Test results from this run are NOT trustworthy — the app will link against a stale or absent " +
        "wrapper, and missing entry points will surface as unrelated test failures.";
}
