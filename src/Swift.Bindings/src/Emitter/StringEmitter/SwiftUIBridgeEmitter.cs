    private static string GenerateSwiftBridge(
        string moduleName,
        List<(ViewBridgeInfo Info, List<BridgeParameter>? Params, AsyncViewPattern? AsyncPattern, bool IsFunctional, List<SynthesizedInitArg>? SynthesizedArgs, List<BridgeModifier>? Modifiers)> bridgeResults,
        HashSet<string>? hintImports = null,
        ModuleEmissionContext? emissionContext = null)
    {
        var sb = new StringBuilder();
        bool hasFunctionalBridge = bridgeResults.Any(r => r.IsFunctional);

        // SwiftUI bridge bodies use UIHostingController (UIKit-only). Gate the file with
        // `#if canImport(UIKit)` so it compiles to an empty translation unit on native
        // macOS — mirrors the C# typed `ViewController` accessor gate
        // (`#if __IOS__ || __TVOS__ || __MACCATALYST__`, see EmitTypedViewControllerAccessor).
        if (hasFunctionalBridge)
        {
            sb.AppendLine("// Auto-generated by SwiftBindings — SwiftUI Bridge");
            sb.AppendLine("#if canImport(UIKit)");
            sb.AppendLine("import UIKit");
            sb.AppendLine("import SwiftUI");
            sb.AppendLine($"import {moduleName}");

            // Extra imports from async patterns
            var extraImports = bridgeResults
                .Where(r => r.AsyncPattern?.ExtraSwiftImports != null)
                .SelectMany(r => r.AsyncPattern!.ExtraSwiftImports)
                .Distinct()
                .Where(m => m != moduleName);
            foreach (var import in extraImports)
            {
                sb.AppendLine($"import {import}");
            }

            // Extra imports from bridge hints
            if (hintImports != null)
            {
                foreach (var import in hintImports.OrderBy(i => i, StringComparer.Ordinal))
                {
                    // Avoid duplicating imports already emitted from async patterns
                    if (!extraImports.Contains(import))
                        sb.AppendLine($"import {import}");
                }
            }

            sb.AppendLine();

            // Shared helpers
            sb.AppendLine("// --- Shared helpers ---");
            sb.AppendLine();
            sb.AppendLine("@discardableResult");
            sb.AppendLine("func SBW_onMainThread<T>(_ block: () -> T) -> T {");
            sb.AppendLine("    if Thread.isMainThread { return block() }");
            sb.AppendLine("    return DispatchQueue.main.sync { block() }");
            sb.AppendLine("}");
            sb.AppendLine();
        }
        else
        {
            sb.AppendLine("// Auto-generated by SwiftBindings — SwiftUI Bridge Templates");
            sb.AppendLine("// These templates require manual completion before use.");
            sb.AppendLine("#if canImport(UIKit)");
            sb.AppendLine("import UIKit");
            sb.AppendLine("import SwiftUI");
            sb.AppendLine($"import {moduleName}");
            sb.AppendLine();
        }

        foreach (var (info, bridgeParams, asyncPattern, isFunctional, synthesizedArgs, modifiers) in bridgeResults)
        {
            if (isFunctional && asyncPattern != null)
            {
                EmitAsyncSwiftBridge(sb, moduleName, info, asyncPattern, emissionContext);
            }
            else if (isFunctional)
            {
                EmitFunctionalSwiftBridge(sb, moduleName, info, bridgeParams!, synthesizedArgs, modifiers, emissionContext);
            }
            else
            {
                EmitSwiftTemplate(sb, moduleName, info);
            }
        }

        sb.AppendLine("#endif // canImport(UIKit)");

        return sb.ToString();
    }

    private static void EmitFunctionalSwiftBridge(
        StringBuilder sb, string moduleName, ViewBridgeInfo info, List<BridgeParameter> bridgeParams,
        List<SynthesizedInitArg>? synthesizedArgs = null, List<BridgeModifier>? modifiers = null,
        ModuleEmissionContext? emissionContext = null)
    {
        var prefix = $"SBW_{moduleName}_{info.ViewName}";
        var sessionClass = $"{prefix}_Session";
        var handlesVar = $"{prefix}_liveHandles";

        sb.AppendLine($"// --- {info.ViewName} ---");
        sb.AppendLine();

        var hasUpdatableParams = bridgeParams.Any(p => p.IsUpdatable);
        var hasModifiers = modifiers != null && modifiers.Count > 0;

        // Always emit State + Wrapper for lifecycle callbacks and universal modifiers.
        EmitSwiftStateClass(sb, prefix, info, bridgeParams, modifiers);
        EmitSwiftWrapperView(sb, prefix, info, bridgeParams, synthesizedArgs, modifiers);

        // Session class — always uses Wrapper pattern.
        var hostedViewType = $"{prefix}_Wrapper";
        sb.AppendLine($"final class {sessionClass} {{");
        sb.AppendLine($"    let state: {prefix}_State");
        sb.AppendLine($"    let hostingController: UIHostingController<{hostedViewType}>");

        // Store callback and array fields
        foreach (var param in bridgeParams)
        {
            if (param.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure)
            {
                sb.AppendLine($"    let {param.Name}Callback: ({param.SwiftAbiType.TrimEnd('?')})?");
                sb.AppendLine($"    let {param.Name}UserData: UnsafeMutableRawPointer?");
            }
            else if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                var successAbi = BuildResultBranchSwiftAbiType(param.ResultSuccessParam!);
                var errorAbi = BuildResultBranchSwiftAbiType(param.ResultErrorParam!);
                sb.AppendLine($"    let {param.Name}SuccessCallback: ({successAbi.TrimEnd('?')})?");
                sb.AppendLine($"    let {param.Name}SuccessUserData: UnsafeMutableRawPointer?");
                sb.AppendLine($"    let {param.Name}ErrorCallback: ({errorAbi.TrimEnd('?')})?");
                sb.AppendLine($"    let {param.Name}ErrorUserData: UnsafeMutableRawPointer?");
            }
            else if (param.Kind == BridgeParameterKind.BridgeArray)
            {
                sb.AppendLine($"    let {param.SwiftName}: {GetSwiftNativeType(param)}");
            }
        }
        sb.AppendLine();

        // Init — failable so out-of-range BoundEnum raw values surface as a nil
        // session/handle (→ C# InvalidOperationException) instead of trapping the process.
        sb.Append($"    init?(");
        var initParams = new List<string>();
        foreach (var param in bridgeParams)
        {
            if (param.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure)
            {
                initParams.Add($"{param.Name}Callback: {param.SwiftAbiType}");
                initParams.Add($"{param.Name}UserData: UnsafeMutableRawPointer?");
            }
            else if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                var successAbi = BuildResultBranchSwiftAbiType(param.ResultSuccessParam!);
                var errorAbi = BuildResultBranchSwiftAbiType(param.ResultErrorParam!);
                initParams.Add($"{param.Name}SuccessCallback: {successAbi}");
                initParams.Add($"{param.Name}SuccessUserData: UnsafeMutableRawPointer?");
                initParams.Add($"{param.Name}ErrorCallback: {errorAbi}");
                initParams.Add($"{param.Name}ErrorUserData: UnsafeMutableRawPointer?");
            }
            else if (param.Kind == BridgeParameterKind.String)
            {
                initParams.Add($"{param.Name}Ptr: UnsafePointer<UInt8>?");
                initParams.Add($"{param.Name}Len: Int");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind == BridgeParameterKind.String)
            {
                initParams.Add($"{param.Name}Ptr: UnsafePointer<UInt8>?");
                initParams.Add($"{param.Name}Len: Int");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                initParams.Add($"{param.Name}Ptr: {param.SwiftAbiType}");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped)
            {
                initParams.Add($"{param.Name}HasValue: Int32");
                initParams.Add($"{param.Name}Value: {param.InnerParameter!.SwiftAbiType}");
            }
            else if (param.IsBindingCodableStruct)
            {
                // Binding<CodableStruct>: ABI carries the value as JSON UTF-8 bytes (ptr+len).
                // The Swift side decodes via JSONDecoder before storing on @Published state.
                initParams.Add($"{param.Name}Ptr: UnsafePointer<UInt8>?");
                initParams.Add($"{param.Name}Len: Int");
            }
            else if (param.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                initParams.Add($"{param.Name}Ptr: {param.SwiftAbiType}");
            }
            else if (param.Kind == BridgeParameterKind.BridgeArray)
            {
                initParams.Add($"{param.Name}Ptr: {param.SwiftAbiType}");
                initParams.Add($"{param.Name}Count: Int");
            }
            else
            {
                initParams.Add($"{param.SwiftName}: {param.SwiftAbiType}");
            }
        }
        sb.Append(string.Join(",\n         ", initParams));
        sb.AppendLine(") {");

        // Store callbacks and arrays
        foreach (var param in bridgeParams)
        {
            if (param.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure)
            {
                sb.AppendLine($"        self.{param.Name}Callback = {param.Name}Callback");
                sb.AppendLine($"        self.{param.Name}UserData = {param.Name}UserData");
            }
            else if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                sb.AppendLine($"        self.{param.Name}SuccessCallback = {param.Name}SuccessCallback");
                sb.AppendLine($"        self.{param.Name}SuccessUserData = {param.Name}SuccessUserData");
                sb.AppendLine($"        self.{param.Name}ErrorCallback = {param.Name}ErrorCallback");
                sb.AppendLine($"        self.{param.Name}ErrorUserData = {param.Name}ErrorUserData");
            }
            else if (!hasUpdatableParams && param.Kind == BridgeParameterKind.BoundStruct)
            {
                if (param.IsObjCBridgeable)
                    // ObjC-bridgeable struct (e.g. URL→NSURL) crosses the ABI as an ObjC
                    // object pointer (C# passes `.Handle`), NOT raw Swift struct bytes. Reading it
                    // via assumingMemoryBound reinterprets an object pointer as struct memory →
                    // type confusion / SIGSEGV. Reconstruct the bridged value instead.
                    sb.AppendLine($"        self.{param.SwiftName} = Unmanaged<AnyObject>.fromOpaque({param.Name}Ptr).takeUnretainedValue() as! {param.BridgeTypeName}");
                else
                    sb.AppendLine($"        self.{param.SwiftName} = {param.Name}Ptr.assumingMemoryBound(to: {param.BridgeTypeName}.self).pointee");
            }
            else if (param.Kind == BridgeParameterKind.BridgeArray)
            {
                var inner = param.InnerParameter!;
                sb.AppendLine($"        if let ptr = {param.Name}Ptr, {param.Name}Count > 0 {{");
                if (inner.Kind == BridgeParameterKind.BoundEnum)
                {
                    // Validate every raw value before constructing the session. A single
                    // out-of-range element fails creation (return nil → C# InvalidOperationException)
                    // rather than trapping the process or silently defaulting/dropping the element.
                    sb.AppendLine($"            var {param.Name}Elements: [{inner.BridgeTypeName}] = []");
                    sb.AppendLine($"            {param.Name}Elements.reserveCapacity({param.Name}Count)");
                    sb.AppendLine($"            for {param.Name}Raw in UnsafeBufferPointer(start: ptr, count: {param.Name}Count) {{");
                    sb.AppendLine($"                guard let {param.Name}Element = {inner.BridgeTypeName}(rawValue: {param.Name}Raw) else {{ return nil }}");
                    sb.AppendLine($"                {param.Name}Elements.append({param.Name}Element)");
                    sb.AppendLine($"            }}");
                    sb.AppendLine($"            self.{param.SwiftName} = {param.Name}Elements");
                }
                else
                {
                    var elementConversion = inner.SwiftConversion != null ? $"$0 {inner.SwiftConversion}" : "$0";
                    sb.AppendLine($"            self.{param.SwiftName} = UnsafeBufferPointer(start: ptr, count: {param.Name}Count).map {{ {elementConversion} }}");
                }
                sb.AppendLine($"        }} else {{");
                sb.AppendLine($"            self.{param.SwiftName} = []");
                sb.AppendLine($"        }}");
            }
        }

        // Capture locals for closure safety
        foreach (var param in bridgeParams)
        {
            if (param.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure)
            {
                sb.AppendLine($"        let cb_{param.Name} = {param.Name}Callback; let ud_{param.Name} = {param.Name}UserData");
            }
            else if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                sb.AppendLine($"        let cb_{param.Name}Success = {param.Name}SuccessCallback; let ud_{param.Name}Success = {param.Name}SuccessUserData");
                sb.AppendLine($"        let cb_{param.Name}Error = {param.Name}ErrorCallback; let ud_{param.Name}Error = {param.Name}ErrorUserData");
            }
        }

        // Always use Wrapper pattern (supports lifecycle + universal modifiers)
        // Convert ABI params to Swift-native values for state
        EmitSwiftStateConversions(sb, bridgeParams);

        // Create state object. The argument LABEL is the bare param name (p.Name), never the
        // backtick-escaped p.SwiftName: Swift accepts a keyword as a bare argument label and
        // warns ("keyword 'X' does not need to be escaped in argument list") if you escape one
        // that is valid bare. The State init declares its external label escaped (p.SwiftName)
        // — a bare call label matches an escaped declared label, so this stays warning-free for
        // a keyword-named param (e.g. `repeat`). The VALUE keeps its escaped/converted form.
        var stateArgs = bridgeParams.Where(p => p.IsUpdatable)
            .Select(p => $"{p.Name}: {GetSwiftConvertedVarName(p)}")
            .ToList();
        sb.AppendLine($"        self.state = {prefix}_State({string.Join(", ", stateArgs)})");

        // Build non-updatable Swift init args for the Wrapper (closures and arrays)
        var wrapperArgs = new List<string> { "state: state" };
        foreach (var param in bridgeParams.Where(p => !p.IsUpdatable))
        {
            if (param.Kind == BridgeParameterKind.VoidClosure)
                wrapperArgs.Add($"{param.Name}: {{\n            DispatchQueue.main.async {{ cb_{param.Name}?(ud_{param.Name}) }}\n        }}");
            else if (param.Kind == BridgeParameterKind.TypedClosure)
                wrapperArgs.Add(BuildTypedClosureViewInitArg(param));
            else if (param.Kind == BridgeParameterKind.ResultClosure)
                wrapperArgs.Add(BuildResultClosureViewInitArg(param));
            else if (param.Kind == BridgeParameterKind.BridgeArray)
                // Wrapper-init call label is the bare param name; the Wrapper init declares its
                // external label escaped (p.SwiftName), and a bare keyword call label matches an
                // escaped declared label warning-free. The VALUE references the escaped local.
                wrapperArgs.Add($"{param.Name}: {param.SwiftName}");
        }
        sb.AppendLine($"        let wrapper = {prefix}_Wrapper({string.Join(", ", wrapperArgs)})");
        sb.AppendLine($"        self.hostingController = UIHostingController(rootView: wrapper)");

        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        // Handle tracking
        sb.AppendLine($"var {handlesVar} = Set<UnsafeMutableRawPointer>()");
        sb.AppendLine();

        // SwiftUI bridge helpers live in the shared `_direct_helper` bucket (also written by ThemeBridgeEmitter). Per-view `prefix` ensures symbol uniqueness across the bucket: one Create/GetViewController/Free per SwiftUI view bridge, prefix collision impossible because each view bridge mints its own.
        // Create function
        emissionContext?.TryAddDirectHelperWrapperSymbol($"{prefix}_Create");
        sb.AppendLine($"@_cdecl(\"{prefix}_Create\")");
        sb.Append($"public func {prefix}_Create(");
        var createParams = new List<string>();
        foreach (var param in bridgeParams)
        {
            if (param.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure)
            {
                createParams.Add($"_ {param.Name}Callback: {param.SwiftAbiType}");
                createParams.Add($"_ {param.Name}UserData: UnsafeMutableRawPointer?");
            }
            else if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                var successAbi = BuildResultBranchSwiftAbiType(param.ResultSuccessParam!);
                var errorAbi = BuildResultBranchSwiftAbiType(param.ResultErrorParam!);
                createParams.Add($"_ {param.Name}SuccessCallback: {successAbi}");
                createParams.Add($"_ {param.Name}SuccessUserData: UnsafeMutableRawPointer?");
                createParams.Add($"_ {param.Name}ErrorCallback: {errorAbi}");
                createParams.Add($"_ {param.Name}ErrorUserData: UnsafeMutableRawPointer?");
            }
            else if (param.Kind == BridgeParameterKind.String)
            {
                createParams.Add($"_ {param.Name}Ptr: UnsafePointer<UInt8>?");
                createParams.Add($"_ {param.Name}Len: Int");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind == BridgeParameterKind.String)
            {
                createParams.Add($"_ {param.Name}Ptr: UnsafePointer<UInt8>?");
                createParams.Add($"_ {param.Name}Len: Int");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                createParams.Add($"_ {param.Name}Ptr: {param.SwiftAbiType}");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped)
            {
                createParams.Add($"_ {param.Name}HasValue: Int32");
                createParams.Add($"_ {param.Name}Value: {param.InnerParameter!.SwiftAbiType}");
            }
            else if (param.IsBindingCodableStruct)
            {
                createParams.Add($"_ {param.Name}Ptr: UnsafePointer<UInt8>?");
                createParams.Add($"_ {param.Name}Len: Int");
            }
            else if (param.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                createParams.Add($"_ {param.Name}Ptr: {param.SwiftAbiType}");
            }
            else if (param.Kind == BridgeParameterKind.BridgeArray)
            {
                createParams.Add($"_ {param.Name}Ptr: {param.SwiftAbiType}");
                createParams.Add($"_ {param.Name}Count: Int");
            }
            else
            {
                createParams.Add($"_ {param.SwiftName}: {param.SwiftAbiType}");
            }
        }
        sb.AppendLine(string.Join(",\n    ", createParams));
        sb.AppendLine(") -> UnsafeMutableRawPointer? {");
        sb.AppendLine("    return SBW_onMainThread {");

        // Build session init call
        var sessionArgs = new List<string>();
        foreach (var param in bridgeParams)
        {
            if (param.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure)
            {
                sessionArgs.Add($"{param.Name}Callback: {param.Name}Callback");
                sessionArgs.Add($"{param.Name}UserData: {param.Name}UserData");
            }
            else if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                sessionArgs.Add($"{param.Name}SuccessCallback: {param.Name}SuccessCallback");
                sessionArgs.Add($"{param.Name}SuccessUserData: {param.Name}SuccessUserData");
                sessionArgs.Add($"{param.Name}ErrorCallback: {param.Name}ErrorCallback");
                sessionArgs.Add($"{param.Name}ErrorUserData: {param.Name}ErrorUserData");
            }
            else if (param.Kind == BridgeParameterKind.String)
            {
                sessionArgs.Add($"{param.Name}Ptr: {param.Name}Ptr");
                sessionArgs.Add($"{param.Name}Len: {param.Name}Len");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind == BridgeParameterKind.String)
            {
                sessionArgs.Add($"{param.Name}Ptr: {param.Name}Ptr");
                sessionArgs.Add($"{param.Name}Len: {param.Name}Len");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                sessionArgs.Add($"{param.Name}Ptr: {param.Name}Ptr");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped)
            {
                sessionArgs.Add($"{param.Name}HasValue: {param.Name}HasValue");
                sessionArgs.Add($"{param.Name}Value: {param.Name}Value");
            }
            else if (param.IsBindingCodableStruct)
            {
                sessionArgs.Add($"{param.Name}Ptr: {param.Name}Ptr");
                sessionArgs.Add($"{param.Name}Len: {param.Name}Len");
            }
            else if (param.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                sessionArgs.Add($"{param.Name}Ptr: {param.Name}Ptr");
            }
            else if (param.Kind == BridgeParameterKind.BridgeArray)
            {
                sessionArgs.Add($"{param.Name}Ptr: {param.Name}Ptr");
                sessionArgs.Add($"{param.Name}Count: {param.Name}Count");
            }
            else
            {
                // Argument LABEL is the bare param name; the VALUE (an identifier reference to
                // the cdecl param) stays backtick-escaped. Escaping a keyword as a call-site
                // label emits a "does not need to be escaped in argument list" warning, while a
                // bare label still matches the session init's escaped declared label.
                sessionArgs.Add($"{param.Name}: {param.SwiftName}");
            }
        }

        sb.AppendLine($"        guard let session = {sessionClass}(");
        sb.AppendLine($"            {string.Join(",\n            ", sessionArgs)}) else {{ return nil }}");
        sb.AppendLine($"        let handle = Unmanaged.passRetained(session).toOpaque()");
        sb.AppendLine($"        {handlesVar}.insert(handle)");
        sb.AppendLine($"        return handle");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        // SwiftUI bridge helpers live in the shared `_direct_helper` bucket (also written by ThemeBridgeEmitter). Per-view `prefix` ensures symbol uniqueness across the bucket: one Create/GetViewController/Free per SwiftUI view bridge, prefix collision impossible because each view bridge mints its own.
        // GetViewController function
        emissionContext?.TryAddDirectHelperWrapperSymbol($"{prefix}_GetViewController");
        sb.AppendLine($"@_cdecl(\"{prefix}_GetViewController\")");
        sb.AppendLine($"public func {prefix}_GetViewController(");
        sb.AppendLine($"    _ handle: UnsafeMutableRawPointer?");
        sb.AppendLine(") -> UnsafeMutableRawPointer? {");
        sb.AppendLine("    return SBW_onMainThread {");
        sb.AppendLine($"        guard let handle = handle,");
        sb.AppendLine($"              {handlesVar}.contains(handle) else {{ return nil }}");
        sb.AppendLine($"        let session = Unmanaged<{sessionClass}>");
        sb.AppendLine($"            .fromOpaque(handle).takeUnretainedValue()");
        sb.AppendLine($"        return Unmanaged.passUnretained(session.hostingController).toOpaque()");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();

        // Free function — must never block on main from a non-main caller.
        // The .NET finalizer thread invokes this while the main thread is parked
        // inside GC.WaitForPendingFinalizers(); SBW_onMainThread's sync dispatch
        // would deadlock. Off-main calls dispatch async so the finalizer thread
        // returns immediately; on-main calls (explicit Dispose) still run inline
        // to preserve the synchronous-cleanup contract. Caller passes a buffer of
        // managed GCHandle IntPtrs that the Swift session still references via
        // user-data pointers (lifecycle / closure trampolines); we invoke the
        // supplied free callback only after Unmanaged.release completes, so the
        // managed handles outlive any Swift state that may capture them. C# may
        // not free those handles itself after calling _Free because the off-main
        // path returns before release runs.
        // SwiftUI bridge helpers live in the shared `_direct_helper` bucket (also written by ThemeBridgeEmitter). Per-view `prefix` ensures symbol uniqueness across the bucket: one Create/GetViewController/Free per SwiftUI view bridge, prefix collision impossible because each view bridge mints its own.
        emissionContext?.TryAddDirectHelperWrapperSymbol($"{prefix}_Free");
        sb.AppendLine($"@_cdecl(\"{prefix}_Free\")");
        sb.AppendLine($"public func {prefix}_Free(");
        sb.AppendLine($"    _ handle: UnsafeMutableRawPointer?,");
        sb.AppendLine($"    _ handleBuffer: UnsafeMutableRawPointer?,");
        sb.AppendLine($"    _ handleCount: Int32,");
        sb.AppendLine($"    _ postReleaseFreeFn: UnsafeMutableRawPointer?");
        sb.AppendLine($") {{");
        sb.AppendLine($"    let release: () -> Void = {{");
        sb.AppendLine($"        if let handle = handle, {handlesVar}.remove(handle) != nil {{");
        sb.AppendLine($"            Unmanaged<{sessionClass}>.fromOpaque(handle).release()");
        sb.AppendLine($"        }}");
        sb.AppendLine($"        if let fnPtr = postReleaseFreeFn {{");
        sb.AppendLine($"            typealias FreeFn = @convention(c) (UnsafeMutableRawPointer?, Int32) -> Void");
        sb.AppendLine($"            let fn = unsafeBitCast(fnPtr, to: FreeFn.self)");
        sb.AppendLine($"            fn(handleBuffer, handleCount)");
        sb.AppendLine($"        }}");
        sb.AppendLine($"    }}");
        sb.AppendLine($"    if Thread.isMainThread {{ release() }}");
        sb.AppendLine($"    else {{ DispatchQueue.main.async(execute: release) }}");
        sb.AppendLine("}");
        sb.AppendLine();

        // Update functions for updatable params
        if (hasUpdatableParams)
        {
            EmitSwiftUpdateFunctions(sb, prefix, sessionClass, handlesVar, bridgeParams, emissionContext);
        }

        // Read functions for Binding<Codable> params (Swift -> C# pull-side observability)
        var codableBindingParams = bridgeParams.Where(p => p.IsBindingCodableStruct).ToList();
        if (codableBindingParams.Count > 0)
        {
            EmitSwiftReadFunctions(sb, prefix, sessionClass, handlesVar, codableBindingParams, emissionContext);
        }

        // Modifier Set functions
        if (hasModifiers)
        {
            EmitSwiftModifierSetFunctions(sb, prefix, sessionClass, handlesVar, modifiers!, emissionContext);
        }

        // Lifecycle Set function.
        EmitSwiftLifecycleSetFunction(sb, prefix, sessionClass, handlesVar, emissionContext);

        // Universal modifier Set functions — skip any that collide with view-specific modifiers.
        var modifierSetNames = modifiers?.Select(m => $"Set{m.PascalName}").ToHashSet() ?? new HashSet<string>();
        EmitSwiftUniversalModifierSetFunctions(sb, prefix, sessionClass, handlesVar, modifierSetNames, emissionContext);

        // Presentation helpers.
        EmitSwiftPresentationFunctions(sb, prefix, sessionClass, handlesVar, emissionContext);
    }

