                MethodName = $"Read{pascalName}Json",
                ReturnType = "IntPtr",
                ParametersString = "IntPtr handle, out nint outLen",
                CallingConvention = PInvokeCallingConvention.Cdecl,
                Visibility = PInvokeVisibility.Internal,
                EmissionContext = emissionContext,
                EnforceWrapperContract = true
            }))
                sb.AppendLine($"        {line}");
        }

        sb.AppendLine();
        foreach (var line in PInvokeEmitHelper.FormatDeclarationLines(new PInvokeEmissionInfo
        {
            LibraryPath = bridgeLib,
            EntryPoint = $"{prefix}_FreeJsonBuffer",
            MethodName = "FreeJsonBuffer",
            ReturnType = "void",
            ParametersString = "IntPtr ptr",
            CallingConvention = PInvokeCallingConvention.Cdecl,
            Visibility = PInvokeVisibility.Internal,
            EmissionContext = emissionContext,
            EnforceWrapperContract = true
        }))
            sb.AppendLine($"        {line}");
    }

    /// <summary>
    /// Emits C# Read methods on the Session class for each Binding&lt;Codable&gt; param.
    /// Calls into Swift, copies the returned buffer, frees it, and decodes via the
    /// generated DecodeFromJson static.
    /// </summary>
    private static void EmitCSharpReadMethods(
        StringBuilder sb, ViewBridgeInfo info, List<BridgeParameter> codableBindingParams)
    {
        foreach (var param in codableBindingParams)
        {
            var pascalName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..];
            var factoryType = GetFactoryParamType(param);

            sb.AppendLine($"        public {factoryType} Read{pascalName}()");
            sb.AppendLine("        {");
            sb.AppendLine($"            var ptr = {info.ViewName}BridgeNativeMethods.Read{pascalName}Json(Handle, out var len);");
            // The Swift reader allocates the buffer before checking length, so a non-null ptr
            // with len <= 0 is reachable in principle. Free the allocation inside the finally
            // so the error path never leaks.
            sb.AppendLine("            if (ptr == IntPtr.Zero)");
            sb.AppendLine($"                throw new InvalidOperationException(\"Read{pascalName}: Swift returned null buffer.\");");
            sb.AppendLine("            try");
            sb.AppendLine("            {");
            sb.AppendLine("                if (len <= 0)");
            sb.AppendLine($"                    throw new InvalidOperationException(\"Read{pascalName}: Swift returned empty buffer.\");");
            sb.AppendLine("                var bytes = new byte[(int)len];");
            sb.AppendLine("                Marshal.Copy(ptr, bytes, 0, bytes.Length);");
            sb.AppendLine($"                return {factoryType}.DecodeFromJson(bytes);");
            sb.AppendLine("            }");
            sb.AppendLine("            finally");
            sb.AppendLine("            {");
            sb.AppendLine($"                {info.ViewName}BridgeNativeMethods.FreeJsonBuffer(ptr);");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();
        }
    }

    /// <summary>
    /// Emits C# Update methods on the Session class for each updatable param.
    /// </summary>
    private static void EmitCSharpUpdateMethods(
        StringBuilder sb, ViewBridgeInfo info, List<BridgeParameter> bridgeParams)
    {
        foreach (var param in bridgeParams.Where(p => p.IsUpdatable))
        {
            var pascalName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..];
            var factoryType = GetFactoryParamType(param);

            if (param.Kind == BridgeParameterKind.String ||
                (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind == BridgeParameterKind.String))
            {
                // String update: UTF-8 encode + fixed
                var isOptional = param.Kind == BridgeParameterKind.OptionalWrapped;
                sb.AppendLine($"        public unsafe void Update{pascalName}({factoryType} newValue)");
                sb.AppendLine("        {");
                if (isOptional)
                {
                    sb.AppendLine("            if (newValue == null)");
                    sb.AppendLine("            {");
                    sb.AppendLine($"                {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, IntPtr.Zero, 0);");
                    sb.AppendLine("                return;");
                    sb.AppendLine("            }");
                }
                sb.AppendLine($"            var bytes = Encoding.UTF8.GetBytes(newValue ?? \"\");");
                sb.AppendLine("            fixed (byte* ptr = bytes)");
                sb.AppendLine($"                {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, (IntPtr)ptr, bytes.Length);");
                sb.AppendLine("        }");
                sb.AppendLine();
            }
            else if (param.Kind == BridgeParameterKind.BoundEnum)
            {
                sb.AppendLine($"        public void Update{pascalName}({factoryType} newValue) =>");
                if (param.IsSimpleEnum)
                    sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, ({param.CSharpPInvokeType})newValue);");
                else
                    sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, newValue.RawValue);");
                sb.AppendLine();
            }
            else if (param.IsBindingCodableStruct)
            {
                // Binding<CodableStruct>: encode newValue to JSON UTF-8 via the generated
                // EncodeToJson() member (emitted by CodableJsonEmitter on the same struct),
                // pin the byte[] for the P/Invoke. Throws ArgumentNullException for a null
                // value because Binding<NonOptional> cannot hold nil on the Swift side.
                sb.AppendLine($"        public unsafe void Update{pascalName}({factoryType} newValue)");
                sb.AppendLine("        {");
                sb.AppendLine("            ArgumentNullException.ThrowIfNull(newValue);");
                sb.AppendLine("            var bytes = newValue.EncodeToJson();");
                sb.AppendLine("            fixed (byte* ptr = bytes)");
                sb.AppendLine($"                {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, (IntPtr)ptr, bytes.Length);");
                sb.AppendLine("        }");
                sb.AppendLine();
            }
            else if (param.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                var handleExpr = param.IsObjCBridgeable ? "newValue.Handle" : "newValue.Payload.DangerousGetHandle()";
                sb.AppendLine($"        public void Update{pascalName}({factoryType} newValue) =>");
                sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, {handleExpr});");
                sb.AppendLine();
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                var innerBridgeable = param.InnerParameter?.IsObjCBridgeable == true;
                var handleExpr = innerBridgeable ? "newValue?.Handle ?? IntPtr.Zero" : "newValue?.Payload.DangerousGetHandle() ?? IntPtr.Zero";
                sb.AppendLine($"        public void Update{pascalName}({factoryType} newValue) =>");
                sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, {handleExpr});");
                sb.AppendLine();
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped)
            {
                var inner = param.InnerParameter!;
                sb.AppendLine($"        public void Update{pascalName}({factoryType} newValue)");
                sb.AppendLine("        {");
                if (inner.Kind == BridgeParameterKind.BoundEnum)
                {
                    if (inner.IsSimpleEnum)
                    {
                        sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, newValue.HasValue ? 1 : 0, newValue.HasValue ? ({inner.CSharpPInvokeType})newValue.Value : 0);");
                    }
                    else
                    {
                        sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, newValue != null ? 1 : 0, newValue?.RawValue ?? 0);");
                    }
                }
                else if (inner.CSharpConversion != null) // Bool
                {
                    sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, newValue.HasValue ? 1 : 0, newValue.HasValue ? (newValue.Value {inner.CSharpConversion}) : 0);");
                }
                else
                {
                    sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, newValue.HasValue ? 1 : 0, newValue ?? 0);");
                }
                sb.AppendLine("        }");
                sb.AppendLine();
            }
            else if (param.CSharpConversion != null)
            {
                // Bool: value ? 1 : 0
                sb.AppendLine($"        public void Update{pascalName}({factoryType} newValue) =>");
                sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, newValue {param.CSharpConversion});");
                sb.AppendLine();
            }
            else
            {
                sb.AppendLine($"        public void Update{pascalName}({factoryType} newValue) =>");
                sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Update{pascalName}(Handle, newValue);");
                sb.AppendLine();
            }
        }
    }

    /// <summary>
    /// Emits C# BindTo/Unbind/OnBoundPropertyChanged methods for INotifyPropertyChanged binding.
    /// Only emitted for views with updatable parameters.
    /// </summary>
    private static void EmitCSharpObservableBindingMethods(
        StringBuilder sb, ViewBridgeInfo info, List<BridgeParameter> bridgeParams)
    {
        var updatableParams = bridgeParams.Where(p => p.IsUpdatable).ToList();
        if (updatableParams.Count == 0)
            return;

        // BindTo — generic with DAM on T for best-effort trim safety (covers common case where
        // T is the concrete VM type). Property resolution uses viewModel.GetType() (runtime type)
        // so base-typed call sites like `BindTo((INotifyPropertyChanged)vm)` still work correctly.
        // The IL2075 pragma covers the known .NET trimming gap where GetType() returns a Type without
        // DAM annotations — same limitation as WPF/MAUI data binding. Dispatchers are parameterless
        // Action closures capturing the viewModel + PropertyInfo, so the handler has zero reflection.
        sb.AppendLine("        /// <summary>Binds a view model's properties to this session's updatable parameters.</summary>");
        sb.AppendLine("        public void BindTo<[System.Diagnostics.CodeAnalysis.DynamicallyAccessedMembers(System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicProperties)] T>(T viewModel) where T : System.ComponentModel.INotifyPropertyChanged");
        sb.AppendLine("        {");
        sb.AppendLine("            ObjectDisposedException.ThrowIf(_disposed, this);");
        sb.AppendLine("            if (_boundViewModel != null)");
        sb.AppendLine("                throw new InvalidOperationException(\"Already bound to a view model. Call Unbind() first.\");");
        sb.AppendLine("#pragma warning disable IL2075 // viewModel.GetType() resolves runtime type for base-typed call sites; DAM on T covers direct-typed calls");
        sb.AppendLine("            _propertyDispatchers = new System.Collections.Generic.Dictionary<string, Action>(StringComparer.OrdinalIgnoreCase);");
        foreach (var param in updatableParams)
        {
            var pascalName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..];
            var castExpr = GetDispatcherValueCast(param);
            sb.AppendLine($"            var prop{pascalName} = viewModel.GetType().GetProperty(\"{pascalName}\");");
            sb.AppendLine($"            if (prop{pascalName} != null)");
            sb.AppendLine($"                _propertyDispatchers[\"{pascalName}\"] = () => Update{pascalName}({castExpr.Replace("value", $"prop{pascalName}.GetValue(viewModel)")});");
        }
        sb.AppendLine("#pragma warning restore IL2075");
        sb.AppendLine("            _boundViewModel = viewModel;");
        sb.AppendLine("            _boundViewModel.PropertyChanged += OnBoundPropertyChanged;");
        sb.AppendLine("        }");
        sb.AppendLine();

        // Unbind
        sb.AppendLine("        public void Unbind()");
        sb.AppendLine("        {");
        sb.AppendLine("            if (_boundViewModel != null)");
        sb.AppendLine("            {");
        sb.AppendLine("                _boundViewModel.PropertyChanged -= OnBoundPropertyChanged;");
        sb.AppendLine("                _boundViewModel = null;");
        sb.AppendLine("                _propertyDispatchers = null;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();

        // OnBoundPropertyChanged — zero reflection, just calls pre-built closures.
        sb.AppendLine("        private void OnBoundPropertyChanged(object? sender, System.ComponentModel.PropertyChangedEventArgs e)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (_disposed || _propertyDispatchers == null) return;");
        sb.AppendLine("            if (string.IsNullOrEmpty(e.PropertyName))");
        sb.AppendLine("            {");
        sb.AppendLine("                foreach (var kvp in _propertyDispatchers) kvp.Value();");
        sb.AppendLine("                return;");
        sb.AppendLine("            }");
        sb.AppendLine("            if (_propertyDispatchers.TryGetValue(e.PropertyName, out var dispatch))");
        sb.AppendLine("                dispatch();");
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    /// <summary>
    /// Gets the cast expression for converting a property value (object?) to the expected Update method parameter type.
    /// Used in dispatcher lambdas where 'value' is the property value already extracted via reflection.
    /// </summary>
    private static string GetDispatcherValueCast(BridgeParameter param)
    {
        var factoryType = GetFactoryParamType(param);

        return param.Kind switch
        {
            BridgeParameterKind.String => "(string?)value",
            BridgeParameterKind.Primitive when param.CSharpConversion != null => "(bool)value!",
            BridgeParameterKind.BoundEnum => $"({factoryType})value!",
            BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct => $"({factoryType})value!",
            BridgeParameterKind.OptionalWrapped when param.InnerParameter?.Kind == BridgeParameterKind.String => "(string?)value",
            BridgeParameterKind.OptionalWrapped => $"({factoryType})value",
            _ => $"({factoryType})value!",
        };
    }

    /// <summary>
    /// Emits Swift @_cdecl Set functions for each modifier.
    /// </summary>
    private static void EmitSwiftModifierSetFunctions(
        StringBuilder sb, string prefix, string sessionClass, string handlesVar,
        List<BridgeModifier> modifiers, ModuleEmissionContext? emissionContext)
    {
        foreach (var mod in modifiers)
        {
            var funcName = $"{prefix}_Set{mod.PascalName}";
            // SwiftUI per-modifier setter in `_direct_helper` bucket. funcName combines per-view `prefix` + per-modifier Pascal name — unique within the bridge.
            emissionContext?.TryAddDirectHelperWrapperSymbol(funcName);

            sb.AppendLine($"@_cdecl(\"{funcName}\")");

            var setParams = new List<string> { "_ handle: UnsafeMutableRawPointer?" };
            if (mod.IsParameterless)
            {
                setParams.Add("_ enabled: Int32");
            }
            else
            {
                var param = mod.Parameter!;
                if (param.Kind == BridgeParameterKind.String)
                {
                    setParams.Add("_ newValuePtr: UnsafePointer<UInt8>?");
                    setParams.Add("_ newValueLen: Int");
                }
                else if (param.Kind == BridgeParameterKind.Primitive && param.SwiftConversion == "!= 0")
                {
                    // Bool param: hasValue + value (both Int32)
                    setParams.Add("_ hasValue: Int32");
                    setParams.Add("_ value: Int32");
                }
                else if (param.Kind == BridgeParameterKind.BoundEnum)
                {
                    setParams.Add("_ hasValue: Int32");
                    setParams.Add($"_ value: {param.SwiftAbiType}");
                }
                else
                {
                    // Other primitives: hasValue + value
                    setParams.Add("_ hasValue: Int32");
                    setParams.Add($"_ value: {param.SwiftAbiType}");
                }
            }

            sb.AppendLine($"public func {funcName}(");
            sb.AppendLine($"    {string.Join(",\n    ", setParams)}");
            sb.AppendLine(") {");
            sb.AppendLine("    SBW_onMainThread {");
            sb.AppendLine($"        guard let handle = handle,");
            sb.AppendLine($"              {handlesVar}.contains(handle) else {{ return }}");
            sb.AppendLine($"        let session = Unmanaged<{sessionClass}>");
            sb.AppendLine($"            .fromOpaque(handle).takeUnretainedValue()");

            // Emit assignment
            if (mod.IsParameterless)
            {
                sb.AppendLine($"        session.state.mod_{mod.MethodName} = enabled != 0");
            }
            else
            {
                var param = mod.Parameter!;
                if (param.Kind == BridgeParameterKind.String)
                {
                    sb.AppendLine($"        if let ptr = newValuePtr, newValueLen > 0 {{");
                    sb.AppendLine($"            session.state.mod_{mod.MethodName} = String(bytes: UnsafeBufferPointer(start: ptr, count: newValueLen), encoding: .utf8) ?? \"\"");
                    sb.AppendLine($"        }} else if newValuePtr != nil {{");
                    sb.AppendLine($"            session.state.mod_{mod.MethodName} = \"\"");
                    sb.AppendLine($"        }} else {{");
                    sb.AppendLine($"            session.state.mod_{mod.MethodName} = nil");
                    sb.AppendLine($"        }}");
                }
                else if (param.Kind == BridgeParameterKind.Primitive && param.SwiftConversion == "!= 0")
                {
                    sb.AppendLine($"        session.state.mod_{mod.MethodName} = hasValue != 0 ? (value != 0) : nil");
                }
                else if (param.Kind == BridgeParameterKind.BoundEnum)
                {
                    // A present out-of-range raw value leaves the modifier state unchanged
                    // (return) rather than trapping; a nil Optional (hasValue == 0) clears it.
                    sb.AppendLine($"        if hasValue != 0 {{");
                    sb.AppendLine($"            guard let modCase = {param.BridgeTypeName}(rawValue: value) else {{ return }}");
                    sb.AppendLine($"            session.state.mod_{mod.MethodName} = modCase");
                    sb.AppendLine($"        }} else {{");
                    sb.AppendLine($"            session.state.mod_{mod.MethodName} = nil");
                    sb.AppendLine($"        }}");
                }
                else
                {
                    sb.AppendLine($"        session.state.mod_{mod.MethodName} = hasValue != 0 ? value : nil");
                }
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine();
        }
    }

