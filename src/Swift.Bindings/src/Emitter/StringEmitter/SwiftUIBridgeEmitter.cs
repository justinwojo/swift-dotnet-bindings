    /// <summary>
    /// Merges bridge parameter args with synthesized init args in constructor parameter order.
    /// When synthesizedArgs is null/empty, returns viewInitArgs directly (backward compatible).
    /// </summary>
    internal static List<string> BuildMergedInitArgs(
        MethodDecl? constructor,
        List<BridgeParameter> bridgeParams,
        List<string> viewInitArgs,
        List<SynthesizedInitArg>? synthesizedArgs)
    {
        if (synthesizedArgs == null || synthesizedArgs.Count == 0)
            return viewInitArgs;

        if (constructor == null)
            return viewInitArgs;

        var merged = new List<string>();
        var synthDict = synthesizedArgs.ToDictionary(s => s.ParamName, s => s.SwiftExpression);
        var bridgeArgIndex = 0;

        // Iterate constructor params in order (skip [0] return type)
        for (int i = 1; i < constructor.CSSignature.Count; i++)
        {
            var paramName = constructor.CSSignature[i].Name;

            if (synthDict.TryGetValue(paramName, out var synthExpr))
            {
                // Synthesized arg — use expression verbatim
                merged.Add($"{paramName}: {synthExpr}");
            }
            else if (bridgeArgIndex < viewInitArgs.Count)
            {
                // Bridged arg
                merged.Add(viewInitArgs[bridgeArgIndex]);
                bridgeArgIndex++;
            }
        }

        return merged;
    }

    /// <summary>
    /// Builds the Swift closure expression for a typed closure view init argument.
    /// Generates: paramName: { (arg0: SwiftType, ...) [-> ReturnType] in callbackExpr }
    /// </summary>
    private static string BuildTypedClosureViewInitArg(BridgeParameter param)
    {
        var closureArgs = param.ClosureArguments!;
        var closureReturn = param.ClosureReturn;

        // Build closure parameter declarations: (arg0: Int, arg1: Bool, arg2: String)
        var swiftArgDecls = closureArgs.Select((a, i) =>
            $"arg{i}: {GetSwiftTypeFromAbi(a)}").ToList();
        var argDeclStr = string.Join(", ", swiftArgDecls);

        // Check if we have String, class, or opaque value type args/returns that need special encoding
        var hasStringArgs = closureArgs.Any(a => a.Kind == BridgeParameterKind.String);
        var hasClassArgs = closureArgs.Any(a => a.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct);
        // Note: BoundStruct returns not yet supported (only args). BoundType covers class returns.
        var hasNonPrimitiveReturn = closureReturn?.Kind is BridgeParameterKind.String or BridgeParameterKind.BoundType;

        if (hasStringArgs || hasClassArgs || hasNonPrimitiveReturn)
        {
            return BuildComplexClosureViewInitArg(param, closureArgs, closureReturn, argDeclStr);
        }

        // Build callback invocation args: convert Swift types to ABI types
        var callbackArgs = closureArgs.Select((a, i) =>
            a.CSharpConversion != null ? $"arg{i} {a.CSharpConversion}" : $"arg{i}").ToList();
        callbackArgs.Add($"ud_{param.Name}");
        var callbackArgStr = string.Join(", ", callbackArgs);

        if (closureReturn == null)
        {
            // (args...) -> Void. Wrapper-init call label is the bare param name (matches the
            // Wrapper init's escaped external label warning-free for a keyword param).
            return $"{param.Name}: {{ ({argDeclStr}) in\n" +
                   $"            cb_{param.Name}?({callbackArgStr})\n" +
                   $"        }}";
        }
        else
        {
            // (args...) -> ReturnType
            var swiftReturnType = GetSwiftTypeFromAbi(closureReturn);
            var defaultVal = closureReturn.SwiftAbiType is "Double" or "Float" ? "0.0" : "0";
            var callExpr = $"cb_{param.Name}?({callbackArgStr}) ?? {defaultVal}";

            if (closureReturn.SwiftConversion != null)
                callExpr = $"({callExpr}) {closureReturn.SwiftConversion}";

            return $"{param.Name}: {{ ({argDeclStr}) -> {swiftReturnType} in\n" +
                   $"            {callExpr}\n" +
                   $"        }}";
        }
    }

    /// <summary>
    /// Builds Swift closure body for closures with String or class arguments.
    /// String args are UTF-8 encoded via withUnsafeBufferPointer.
    /// Class args are passed as opaque pointers via Unmanaged.passRetained.
    /// </summary>
    private static string BuildComplexClosureViewInitArg(
        BridgeParameter param, List<BridgeParameter> closureArgs,
        BridgeParameter? closureReturn, string argDeclStr)
    {
        var sb = new StringBuilder();
        var hasReturn = closureReturn != null;

        // Closure signature: with or without return type annotation
        if (hasReturn)
        {
            var swiftReturnType = GetSwiftTypeFromAbi(closureReturn!);
            // Wrapper-init call label is the bare param name (matches escaped decl label).
            sb.Append($"{param.Name}: {{ ({argDeclStr}) -> {swiftReturnType} in\n");
        }
        else
        {
            sb.Append($"{param.Name}: {{ ({argDeclStr}) in\n");
        }

        // Collect String args that need withUnsafeBufferPointer nesting
        var stringArgIndices = new List<int>();
        for (int i = 0; i < closureArgs.Count; i++)
        {
            if (closureArgs[i].Kind == BridgeParameterKind.String)
            {
                sb.Append($"            let arg{i}Bytes = Array(arg{i}.utf8)\n");
                stringArgIndices.Add(i);
            }
        }

        // Collect ObjC-bridgeable BoundStruct args that need withExtendedLifetime nesting:
        // they cross the ABI as ObjC object pointers (Unmanaged.passUnretained) and must be
        // held alive across the synchronous callback, exactly like the Result success branch.
        // Non-ObjC BoundStructs use the heap-allocate path below instead.
        var objcArgIndices = new List<int>();
        for (int i = 0; i < closureArgs.Count; i++)
        {
            if (closureArgs[i].Kind == BridgeParameterKind.BoundStruct && closureArgs[i].IsObjCBridgeable)
                objcArgIndices.Add(i);
        }

        // Guard against nil callback BEFORE heap-allocating BoundStruct args.
        // If cb_ is nil (C# didn't provide a callback), skip the allocation to avoid leaks.
        var hasBoundStructArgs = closureArgs.Any(a => a.Kind == BridgeParameterKind.BoundStruct);
        if (hasBoundStructArgs)
        {
            sb.Append($"            guard cb_{param.Name} != nil else {{ ");
            if (hasReturn)
            {
                var defaultRet = closureReturn!.Kind switch
                {
                    BridgeParameterKind.String => "return \"\"",
                    BridgeParameterKind.BoundType =>
                        $"fatalError(\"SBW: closure callback not provided for non-optional class return\")",
                    _ when closureReturn.SwiftAbiType is "Double" or "Float" => "return 0.0",
                    _ => "return 0",
                };
                if (closureReturn.Kind is not BridgeParameterKind.String and not BridgeParameterKind.BoundType
                    && closureReturn.SwiftConversion != null)
                    defaultRet = $"return {(closureReturn.SwiftAbiType is "Double" or "Float" ? "0.0" : "0")} {closureReturn.SwiftConversion}";
                sb.Append(defaultRet);
            }
            else
            {
                sb.Append("return");
            }
            sb.Append(" }\n");
        }

        // Heap-allocate BoundStruct args (non-frozen enums/structs) — ownership transfers to C#.
        // Uses UnsafeMutableRawPointer.allocate + initializeMemory (not withUnsafePointer,
        // which creates a stack pointer incompatible with NativeMemory.Free on the C# side).
        // Safe from leaks: guarded by cb_ nil check above.
        for (int i = 0; i < closureArgs.Count; i++)
        {
            if (closureArgs[i].Kind == BridgeParameterKind.BoundStruct)
            {
                if (closureArgs[i].IsObjCBridgeable)
                {
                    // An ObjC-bridgeable struct (URL→NSURL, Data→NSData) crosses the ABI as an ObjC
                    // object pointer, NOT raw Swift struct bytes. Heap-allocating it and letting C#
                    // read it via MarshalFromSwift (assumingMemoryBound) reinterprets an object
                    // pointer as struct memory → type confusion / SIGSEGV. Bridge to an object here
                    // and deliver Unmanaged.passUnretained(...).toOpaque() below, held alive across
                    // the synchronous callback by withExtendedLifetime.
                    sb.Append($"            let arg{i}Obj = arg{i} as AnyObject\n");
                    continue;
                }
                var typeName = closureArgs[i].BridgeTypeName;
                sb.Append($"            let arg{i}Ptr = UnsafeMutableRawPointer.allocate(byteCount: MemoryLayout<{typeName}>.size, alignment: MemoryLayout<{typeName}>.alignment)\n");
                if (closureArgs[i].StructProjection == StructProjectionKind.FrozenWithMemory)
                {
                    // A frozen struct with reference-holding fields (ClassWithBufferStruct) is
                    // *copied* by the C# side via InitializeWithCopy into its own SafeHandle-owned
                    // buffer — C# does NOT adopt this pointer (see SwiftMarshal.DestroyWireBufferRetains
                    // docs). Without a Swift-side deinit, the source buffer keeps its +1 retains on the
                    // heap fields, and the allocation itself, forever. Capture the typed pointer and
                    // release+free it via defer (runs after the synchronous C# callback returns, and
                    // after any closure return value is computed). Non-frozen structs/enums ARE adopted
                    // by C#'s SafeHandle, so freeing them here would double-free → gate on FrozenWithMemory.
                    sb.Append($"            let arg{i}Typed = arg{i}Ptr.initializeMemory(as: {typeName}.self, repeating: arg{i}, count: 1)\n");
                    sb.Append($"            defer {{ arg{i}Typed.deinitialize(count: 1); arg{i}Ptr.deallocate() }}\n");
                }
                else
                {
                    sb.Append($"            arg{i}Ptr.initializeMemory(as: {typeName}.self, repeating: arg{i}, count: 1)\n");
                }
            }
        }

        // Open nested withUnsafeBufferPointer blocks for each String arg
        // When the closure has a non-void return, each withUnsafeBufferPointer call must
        // be preceded by `return` so the typed result propagates through all nesting levels.
        var baseIndent = "            ";
        var currentIndent = baseIndent;
        for (int s = 0; s < stringArgIndices.Count; s++)
        {
            var si = stringArgIndices[s];
            var returnPrefix = hasReturn ? "return " : "";
            sb.Append($"{currentIndent}{returnPrefix}arg{si}Bytes.withUnsafeBufferPointer {{ buf{si} in\n");
            currentIndent += "    ";
        }

        // Open a withExtendedLifetime block for each ObjC-bridgeable BoundStruct arg, nested
        // inside the String blocks. passUnretained yields an untracked raw pointer; without this
        // ARC may release the bridged object before the synchronous C# trampoline dereferences
        // it → use-after-free. The `return` prefix propagates a non-void result up.
        for (int o = 0; o < objcArgIndices.Count; o++)
        {
            var oi = objcArgIndices[o];
            var returnPrefix = hasReturn ? "return " : "";
            sb.Append($"{currentIndent}{returnPrefix}withExtendedLifetime(arg{oi}Obj) {{\n");
            currentIndent += "    ";
        }

        // Build callback args: String→(baseAddress, count), Class→Unmanaged,
        // BoundStruct→allocate+initializeMemory, Primitive→direct
        var callbackArgs = new List<string>();
        for (int i = 0; i < closureArgs.Count; i++)
        {
            var a = closureArgs[i];
            if (a.Kind == BridgeParameterKind.String)
            {
                callbackArgs.Add($"buf{i}.baseAddress");
                callbackArgs.Add($"Int(buf{i}.count)");
            }
            else if (a.Kind == BridgeParameterKind.BoundType)
            {
                callbackArgs.Add($"Unmanaged.passRetained(arg{i}).toOpaque()");
            }
            else if (a.Kind == BridgeParameterKind.BoundStruct)
            {
                if (a.IsObjCBridgeable)
                    // ObjC-bridgeable struct: deliver the bridged object pointer (held alive by the
                    // enclosing withExtendedLifetime block). C# reads it via GetNSObject, not VWT.
                    callbackArgs.Add($"Unmanaged.passUnretained(arg{i}Obj).toOpaque()");
                else
                    // Heap-allocate the value type and transfer ownership to C#.
                    // C#'s SwiftSafeHandle will call VWT Destroy + NativeMemory.Free on dispose.
                    callbackArgs.Add($"arg{i}Ptr");
            }
            else if (a.CSharpConversion != null)
            {
                callbackArgs.Add($"arg{i} {a.CSharpConversion}");
            }
            else
            {
                callbackArgs.Add($"arg{i}");
            }
        }
        // String-returning closures: add retLen out-parameter before userData
        if (closureReturn?.Kind == BridgeParameterKind.String)
            callbackArgs.Add("lenPtr");
        callbackArgs.Add($"ud_{param.Name}");
        var callbackArgStr = string.Join(", ", callbackArgs);

        if (hasReturn)
        {
            var isStringReturn = closureReturn!.Kind == BridgeParameterKind.String;
            var isClassReturn = closureReturn.Kind == BridgeParameterKind.BoundType;

            if (isStringReturn)
            {
                // String return: decode UTF-8 buffer returned from C# callback
                sb.Append($"{currentIndent}var retLen: Int = 0\n");
                sb.Append($"{currentIndent}let retPtr = withUnsafeMutablePointer(to: &retLen) {{ lenPtr in\n");
                sb.Append($"{currentIndent}    cb_{param.Name}?({callbackArgStr})\n");
                sb.Append($"{currentIndent}}}\n");
                sb.Append($"{currentIndent}defer {{ retPtr?.deallocate() }}\n");
                sb.Append($"{currentIndent}guard let retBuf = retPtr, retLen > 0 else {{ return \"\" }}\n");
                sb.Append($"{currentIndent}return String(bytes: UnsafeBufferPointer(start: retBuf, count: retLen), encoding: .utf8) ?? \"\"\n");
            }
            else if (isClassReturn)
            {
                // Class return: unwrap Unmanaged pointer with ownership transfer
                var callExpr = $"cb_{param.Name}?({callbackArgStr})";
                sb.Append($"{currentIndent}guard let retPtr = {callExpr} else {{\n");
                sb.Append($"{currentIndent}    fatalError(\"SBW: closure returned null for non-optional class return\")\n");
                sb.Append($"{currentIndent}}}\n");
                sb.Append($"{currentIndent}return Unmanaged<{closureReturn.BridgeTypeName}>.fromOpaque(retPtr).takeRetainedValue()\n");
            }
            else
            {
                // Primitive return: default value + optional chaining + conversion
                var defaultVal = closureReturn.SwiftAbiType is "Double" or "Float" ? "0.0" : "0";
                var callExpr = $"cb_{param.Name}?({callbackArgStr}) ?? {defaultVal}";
                if (closureReturn.SwiftConversion != null)
                    callExpr = $"({callExpr}) {closureReturn.SwiftConversion}";

                // String/ObjC-struct args nest the call inside withUnsafeBufferPointer /
                // withExtendedLifetime blocks, which require `return` to propagate the result up.
                if (stringArgIndices.Count > 0 || objcArgIndices.Count > 0)
                    sb.Append($"{currentIndent}return {callExpr}\n");
                else
                    sb.Append($"{currentIndent}{callExpr}\n");
            }
        }
        else
        {
            sb.Append($"{currentIndent}cb_{param.Name}?({callbackArgStr})\n");
        }

        // Close withExtendedLifetime blocks (innermost — nested inside the String blocks).
        for (int o = objcArgIndices.Count - 1; o >= 0; o--)
        {
            currentIndent = baseIndent + new string(' ', 4 * (stringArgIndices.Count + o));
            sb.Append($"{currentIndent}}}\n");
        }

        // Close nested withUnsafeBufferPointer blocks — inner blocks need `return` propagation
        for (int s = stringArgIndices.Count - 1; s >= 0; s--)
        {
            currentIndent = baseIndent + new string(' ', 4 * s);
            sb.Append($"{currentIndent}}}\n");
        }

        sb.Append($"        }}");
        return sb.ToString();
    }

    /// <summary>
    /// Maps an ABI BridgeParameter back to its Swift type name for closure signatures.
    /// e.g., Int32 with SwiftConversion "!= 0" → Bool; Int → Int; Double → Double
    /// </summary>
    private static string GetSwiftTypeFromAbi(BridgeParameter param)
    {
        if (param.SwiftConversion == "!= 0") return "Bool";
        if (param.Kind == BridgeParameterKind.String) return "String";
        if (param.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct) return param.BridgeTypeName!;
        return param.SwiftAbiType;
    }

    /// <summary>
    /// Opens a FailFast guard around an <c>[UnmanagedCallersOnly]</c> trampoline body. A managed
    /// exception that escapes a UCO frame into native Swift aborts the process with no diagnostic
    /// (SIGABRT); routing it through <c>SwiftClosureMarshaller.FailFastUnhandledClosureException</c>
    /// converts that into a deterministic, attributable crash. Used for trampolines that invoke a
    /// user-supplied delegate with no synchronous error channel back to the caller (SwiftUI
    /// render/event callbacks, lifecycle hooks, fire-and-forget result callbacks). Pair every call
    /// with <see cref="CloseUcoFailFastGuard"/>; the guarded body keeps its existing indentation.
    /// </summary>
    private static void OpenUcoFailFastGuard(StringBuilder sb)
    {
        sb.AppendLine("            try");
        sb.AppendLine("            {");
    }

    /// <summary>
    /// Closes a FailFast guard opened by <see cref="OpenUcoFailFastGuard"/>. The trailing
    /// <c>throw;</c> is required: CS0161 reachability analysis does not honor
    /// <c>[DoesNotReturn]</c>, so a non-void trampoline would otherwise fail to compile.
    /// </summary>
    private static void CloseUcoFailFastGuard(StringBuilder sb)
    {
        sb.AppendLine("            }");
        sb.AppendLine("            catch (global::System.Exception __ex)");
        sb.AppendLine("            {");
        sb.AppendLine("                global::Swift.Runtime.SwiftClosureMarshaller.FailFastUnhandledClosureException(__ex);");
        sb.AppendLine("                throw;");
        sb.AppendLine("            }");
    }

    /// <summary>
    /// Emits a typed closure [UnmanagedCallersOnly] trampoline that unpacks GCHandle → delegate,
    /// converts ABI args to C# types, calls the delegate, and converts the return value back.
    /// </summary>
    private static void EmitTypedClosureTrampoline(StringBuilder sb, BridgeParameter param)
    {
        var trampolineName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..] + "Trampoline";
        var closureArgs = param.ClosureArguments!;
        var closureReturn = param.ClosureReturn;

        // Build trampoline parameters: String args expand to (IntPtr ptr, nint len)
        var trampolineParams = new List<string>();
        foreach (var (a, i) in closureArgs.Select((a, i) => (a, i)))
        {
            if (a.Kind == BridgeParameterKind.String)
            {
                trampolineParams.Add($"IntPtr arg{i}Ptr");
                trampolineParams.Add($"nint arg{i}Len");
            }
            else
            {
                trampolineParams.Add($"{a.CSharpPInvokeType} arg{i}");
            }
        }
        // String-returning closures: add retLen out-parameter before userData
        if (closureReturn?.Kind == BridgeParameterKind.String)
            trampolineParams.Add("IntPtr retLenPtr");
        trampolineParams.Add("IntPtr userData");
        var returnType = closureReturn?.CSharpPInvokeType ?? "void";

        sb.AppendLine($"        [UnmanagedCallersOnly(CallConvs = new[] {{ typeof(global::System.Runtime.CompilerServices.CallConvCdecl) }})]");
        sb.AppendLine($"        private static {returnType} {trampolineName}({string.Join(", ", trampolineParams)})");
        sb.AppendLine("        {");
        OpenUcoFailFastGuard(sb);
        sb.AppendLine("            if (userData != IntPtr.Zero)");
        sb.AppendLine("            {");
        sb.AppendLine("                var h = GCHandle.FromIntPtr(userData);");

        // Build C# delegate type for the cast
        var delegateType = GetCSharpDelegateType(closureArgs, closureReturn);

        var hasStringOrClassArgs = closureArgs.Any(a => a.Kind is BridgeParameterKind.String
                                                                    or BridgeParameterKind.BoundType
                                                                    or BridgeParameterKind.BoundStruct);

        if (hasStringOrClassArgs)
        {
            // String/class/opaque-struct args need decoding before delegate invocation
            foreach (var (a, i) in closureArgs.Select((a, i) => (a, i)))
            {
                if (a.Kind == BridgeParameterKind.String)
                {
                    sb.AppendLine($"                var str{i} = \"\";");
                    sb.AppendLine($"                if (arg{i}Ptr != IntPtr.Zero && arg{i}Len > 0)");
                    sb.AppendLine($"                    unsafe {{ str{i} = Encoding.UTF8.GetString((byte*)arg{i}Ptr, (int)arg{i}Len); }}");
                }
                else if (a.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
                {
                    if (a.Kind == BridgeParameterKind.BoundStruct && a.IsObjCBridgeable)
                        // ObjC-bridgeable struct: the Swift side delivered the bridged object
                        // pointer (Unmanaged.passUnretained). GetNSObject wraps it without ownership
                        // transfer — reading it via MarshalFromSwift (assumingMemoryBound) would
                        // reinterpret an object pointer as raw struct bytes → type confusion.
                        sb.AppendLine($"                var arg{i}Obj = ObjCRuntime.Runtime.GetNSObject<{a.CSharpTypeName}>(arg{i})!;");
                    else
                        sb.AppendLine($"                var arg{i}Obj = ({a.CSharpTypeName})Swift.Runtime.InteropServices.SwiftMarshal.MarshalFromSwift<{a.CSharpTypeName}>(arg{i});");
                }
            }

            // Build delegate args using decoded values
            var delegateArgs = new List<string>();
            for (int i = 0; i < closureArgs.Count; i++)
            {
                var a = closureArgs[i];
                if (a.Kind == BridgeParameterKind.String)
                    delegateArgs.Add($"str{i}");
                else if (a.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
                    delegateArgs.Add($"arg{i}Obj");
                else if (a.SwiftConversion != null)
                    delegateArgs.Add($"arg{i} {a.SwiftConversion}");
                else
                    delegateArgs.Add($"arg{i}");
            }
            var delegateArgStr = string.Join(", ", delegateArgs);

            if (closureReturn == null)
            {
                sb.AppendLine($"                if (h.Target is {delegateType} action)");
                sb.AppendLine($"                    action({delegateArgStr});");
            }
            else
            {
                sb.AppendLine($"                if (h.Target is {delegateType} func)");
                sb.AppendLine("                {");
                sb.AppendLine($"                    var result = func({delegateArgStr});");
                EmitTrampolineReturnEncoding(sb, closureReturn);
                sb.AppendLine("                }");
            }
        }
        else
        {
            // Simple primitive args — direct pass
            var delegateArgs = closureArgs.Select((a, i) =>
                a.SwiftConversion != null ? $"arg{i} {a.SwiftConversion}" : $"arg{i}").ToList();
            var delegateArgStr = string.Join(", ", delegateArgs);

            if (closureReturn == null)
            {
                sb.AppendLine($"                if (h.Target is {delegateType} action)");
                sb.AppendLine($"                    action({delegateArgStr});");
            }
            else
            {
                sb.AppendLine($"                if (h.Target is {delegateType} func)");
                sb.AppendLine("                {");
                sb.AppendLine($"                    var result = func({delegateArgStr});");
                EmitTrampolineReturnEncoding(sb, closureReturn);
                sb.AppendLine("                }");
            }
        }

        sb.AppendLine("            }");
        if (closureReturn != null)
        {
            var defaultReturn = closureReturn.Kind is BridgeParameterKind.String or BridgeParameterKind.BoundType
                ? "IntPtr.Zero" : "0";
            sb.AppendLine($"            return {defaultReturn};");
        }
        CloseUcoFailFastGuard(sb);
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    /// <summary>
    /// Emits the return encoding for a typed closure trampoline based on return type kind.
    /// String return: allocates native buffer, encodes UTF-8. Class return: retains + returns pointer.
    /// </summary>
    private static void EmitTrampolineReturnEncoding(StringBuilder sb, BridgeParameter closureReturn)
    {
        if (closureReturn.Kind == BridgeParameterKind.String)
        {
            // String return: encode to native UTF-8 buffer, write length to out-parameter
            sb.AppendLine("                    var bytes = Encoding.UTF8.GetBytes(result ?? \"\");");
            sb.AppendLine("                    if (bytes.Length > 0)");
            sb.AppendLine("                    {");
            sb.AppendLine("                        unsafe");
            sb.AppendLine("                        {");
            sb.AppendLine("                            var nativePtr = (byte*)NativeMemory.Alloc((nuint)bytes.Length);");
            sb.AppendLine("                            bytes.CopyTo(new Span<byte>(nativePtr, bytes.Length));");
            sb.AppendLine("                            *(nint*)retLenPtr = bytes.Length;");
            sb.AppendLine("                            return (IntPtr)nativePtr;");
            sb.AppendLine("                        }");
            sb.AppendLine("                    }");
            sb.AppendLine("                    unsafe { *(nint*)retLenPtr = 0; }");
            sb.AppendLine("                    return IntPtr.Zero;");
        }
        else if (closureReturn.Kind == BridgeParameterKind.BoundType)
        {
            // Class return: retain the Swift object and return its pointer
            sb.AppendLine("                    if (result != null)");
            sb.AppendLine("                    {");
            sb.AppendLine("                        var ptr = result.Payload.DangerousGetHandle();");
            sb.AppendLine("                        Swift.Runtime.Arc.Retain(ptr);");
            sb.AppendLine("                        return ptr;");
            sb.AppendLine("                    }");
            sb.AppendLine("                    return IntPtr.Zero;");
        }
        else if (closureReturn.CSharpConversion != null)
        {
            sb.AppendLine($"                    return result {closureReturn.CSharpConversion};");
        }
        else
        {
            sb.AppendLine($"                    return result;");
        }
    }

    /// <summary>
    /// Gets the C# delegate type for a typed closure (e.g., Action&lt;nint, bool&gt; or Func&lt;nint, bool&gt;).
    /// </summary>
    private static string GetCSharpDelegateType(List<BridgeParameter> closureArgs, BridgeParameter? closureReturn)
    {
        var argTypes = closureArgs.Select(GetClosureArgCSharpType).ToList();

        if (closureReturn == null)
        {
            return argTypes.Count == 0 ? "Action" : $"Action<{string.Join(", ", argTypes)}>";
        }
        else
        {
            var returnType = GetFactoryParamType(closureReturn);
            argTypes.Add(returnType);
            return $"Func<{string.Join(", ", argTypes)}>";
        }
    }

    /// <summary>
    /// Gets the idiomatic C# type for a closure argument used in delegate types.
    /// String → "string", BoundType → fully-qualified class name, others → same as factory param.
    /// </summary>
    private static string GetClosureArgCSharpType(BridgeParameter param) => param.Kind switch
    {
        BridgeParameterKind.String => "string",
        BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct => param.CSharpTypeName!,
        _ => GetFactoryParamType(param),
    };

    /// <summary>
    /// Gets the C# factory parameter type for a typed closure (e.g., Action&lt;nint&gt;? or Func&lt;nint, bool&gt;?).
    /// </summary>
    private static string GetTypedClosureFactoryType(BridgeParameter param)
    {
        var closureArgs = param.ClosureArguments!;
        var closureReturn = param.ClosureReturn;
        return GetCSharpDelegateType(closureArgs, closureReturn) + "?";
    }

    /// <summary>
    /// Gets the delegate* unmanaged function pointer type for a closure parameter.
    /// VoidClosure: delegate* unmanaged[Cdecl]&lt;IntPtr, void&gt;
    /// TypedClosure: delegate* unmanaged[Cdecl]&lt;argTypes..., IntPtr, returnType&gt;
    /// </summary>
    private static string GetClosureFunctionPointerType(BridgeParameter param)
    {
        if (param.Kind == BridgeParameterKind.VoidClosure)
            return "delegate* unmanaged[Cdecl]<IntPtr, void>";

        var closureArgs = param.ClosureArguments!;
        var closureReturn = param.ClosureReturn;
        var fnPtrTypes = new List<string>();
        foreach (var a in closureArgs)
        {
            if (a.Kind == BridgeParameterKind.String)
            {
                fnPtrTypes.Add("IntPtr"); // ptr
                fnPtrTypes.Add("nint");   // len
            }
            else
            {
                fnPtrTypes.Add(a.CSharpPInvokeType);
            }
        }
        // String-returning closures: add retLen out-parameter before userData
        if (closureReturn?.Kind == BridgeParameterKind.String)
            fnPtrTypes.Add("IntPtr"); // retLenPtr
        fnPtrTypes.Add("IntPtr"); // userData
        fnPtrTypes.Add(closureReturn?.CSharpPInvokeType ?? "void"); // return type
        return $"delegate* unmanaged[Cdecl]<{string.Join(", ", fnPtrTypes)}>";
    }

    /// <summary>
    /// Builds the Swift @convention(c) ABI type for one branch of a ResultClosure callback.
    /// </summary>
    private static string BuildResultBranchSwiftAbiType(BridgeParameter branchParam)
    {
        var abiArgs = new List<string>();
        if (branchParam.Kind == BridgeParameterKind.String)
        {
            abiArgs.Add("UnsafePointer<UInt8>?");
            abiArgs.Add("Int"); // length
        }
        else
        {
            abiArgs.Add(branchParam.SwiftAbiType);
        }
        abiArgs.Add("UnsafeMutableRawPointer?"); // userData
        return $"(@convention(c) ({string.Join(", ", abiArgs)}) -> Void)?";
    }

    /// <summary>
    /// Builds the C# delegate* unmanaged function pointer type for one branch of a ResultClosure.
    /// </summary>
    private static string BuildResultBranchFnPtrType(BridgeParameter branchParam)
    {
        var fnPtrTypes = new List<string>();
        if (branchParam.Kind == BridgeParameterKind.String)
        {
            fnPtrTypes.Add("IntPtr"); // ptr
            fnPtrTypes.Add("nint");   // len
        }
        else
        {
            fnPtrTypes.Add(branchParam.CSharpPInvokeType);
        }
        fnPtrTypes.Add("IntPtr"); // userData
        fnPtrTypes.Add("void");   // return
        return $"delegate* unmanaged[Cdecl]<{string.Join(", ", fnPtrTypes)}>";
    }

    /// <summary>
    /// Gets the Swift native Result type string for a ResultClosure parameter.
    /// e.g., "Result&lt;ScanResult, ScanError&gt;" for two BoundType branches.
    /// </summary>
    private static string GetSwiftResultType(BridgeParameter param)
    {
        var successType = GetSwiftTypeFromAbi(param.ResultSuccessParam!);
        var errorType = GetSwiftTypeFromAbi(param.ResultErrorParam!);
        return $"Result<{successType}, {errorType}>";
    }

    /// <summary>
    /// Emits the ResultClosure [UnmanagedCallersOnly] trampoline for one branch (success or error).
    /// </summary>
    private static void EmitResultBranchTrampoline(StringBuilder sb, string trampolineName, BridgeParameter branchParam)
    {
        var trampolineParams = new List<string>();
        if (branchParam.Kind == BridgeParameterKind.String)
        {
            trampolineParams.Add("IntPtr valuePtr");
            trampolineParams.Add("nint valueLen");
        }
        else
        {
            trampolineParams.Add($"{branchParam.CSharpPInvokeType} value");
        }
        trampolineParams.Add("IntPtr userData");

        sb.AppendLine($"        [UnmanagedCallersOnly(CallConvs = new[] {{ typeof(global::System.Runtime.CompilerServices.CallConvCdecl) }})]");
        sb.AppendLine($"        private static void {trampolineName}({string.Join(", ", trampolineParams)})");
        sb.AppendLine("        {");
        OpenUcoFailFastGuard(sb);
        sb.AppendLine("            if (userData != IntPtr.Zero)");
        sb.AppendLine("            {");
        sb.AppendLine("                var h = GCHandle.FromIntPtr(userData);");

        var csharpType = GetClosureArgCSharpType(branchParam);
        if (branchParam.Kind == BridgeParameterKind.String)
        {
            sb.AppendLine($"                if (h.Target is Action<{csharpType}> action)");
            sb.AppendLine("                {");
            sb.AppendLine("                    var str = \"\";");
            sb.AppendLine("                    if (valuePtr != IntPtr.Zero && valueLen > 0)");
            sb.AppendLine("                        unsafe { str = Encoding.UTF8.GetString((byte*)valuePtr, (int)valueLen); }");
            sb.AppendLine("                    action(str);");
            sb.AppendLine("                }");
        }
        else if (branchParam.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
        {
            sb.AppendLine($"                if (h.Target is Action<{csharpType}> action)");
            sb.AppendLine("                {");
            if (branchParam.IsObjCBridgeable)
            {
                // ObjC class: value IS the raw object handle (from Unmanaged.passUnretained).
                // GetNSObject wraps it without ownership transfer — safe because the Swift
                // Result case binding keeps the object alive for the callback duration.
                sb.AppendLine($"                    var obj = ObjCRuntime.Runtime.GetNSObject<{branchParam.CSharpTypeName}>(value)!;");
            }
            else
            {
                sb.AppendLine($"                    var obj = ({branchParam.CSharpTypeName})Swift.Runtime.InteropServices.SwiftMarshal.MarshalFromSwift<{branchParam.CSharpTypeName}>(value);");
            }
            sb.AppendLine("                    action(obj);");
            sb.AppendLine("                }");
        }
        else
        {
            // Primitive
            var delegateArg = branchParam.SwiftConversion != null ? $"value {branchParam.SwiftConversion}" : "value";
            sb.AppendLine($"                if (h.Target is Action<{csharpType}> action)");
            sb.AppendLine($"                    action({delegateArg});");
        }

        sb.AppendLine("            }");
        CloseUcoFailFastGuard(sb);
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    /// <summary>
    /// Builds the Swift closure body for the wrapper init arg of a ResultClosure parameter.
    /// The closure switches on .success/.failure and calls the appropriate C callback.
    /// </summary>
    private static string BuildResultClosureViewInitArg(BridgeParameter param)
    {
        var sb = new StringBuilder();
        var resultType = GetSwiftResultType(param);
        var successParam = param.ResultSuccessParam!;
        var errorParam = param.ResultErrorParam!;

        // Wrapper-init call label is the bare param name (matches escaped decl label).
        sb.Append($"{param.Name}: {{ (result: {resultType}) in\n");

        // Guard against nil callbacks — if C# didn't provide either callback, skip
        sb.Append($"            switch result {{\n");

        // .success branch
        sb.Append($"            case .success(let value):\n");
        sb.Append(BuildResultBranchCallbackInvocation("Success", successParam, param.Name));

        // .failure branch
        sb.Append($"            case .failure(let error):\n");
        sb.Append(BuildResultBranchCallbackInvocation("Error", errorParam, param.Name));

        sb.Append($"            }}\n");
        sb.Append($"        }}");
        return sb.ToString();
    }

    /// <summary>
    /// Builds the Swift callback invocation for one branch of a Result closure.
    /// </summary>
    private static string BuildResultBranchCallbackInvocation(string branch, BridgeParameter branchParam, string closureName)
    {
        var sb = new StringBuilder();
        var varName = branch == "Success" ? "value" : "error";
        var cbName = $"cb_{closureName}{branch}";
        var udName = $"ud_{closureName}{branch}";

        if (branchParam.Kind == BridgeParameterKind.String)
        {
            sb.Append($"                let {varName}Bytes = Array({varName}.utf8)\n");
            sb.Append($"                {varName}Bytes.withUnsafeBufferPointer {{ buf in\n");
            sb.Append($"                    {cbName}?(buf.baseAddress, Int(buf.count), {udName})\n");
            sb.Append($"                }}\n");
        }
        else if (branchParam.Kind == BridgeParameterKind.BoundType)
        {
            if (branchParam.IsObjCBridgeable)
            {
                // ObjC class: passUnretained is safe because the Swift Result case
                // binding keeps the object alive for the callback duration. C# uses
                // GetNSObject to wrap without ownership transfer.
                sb.Append($"                {cbName}?(Unmanaged.passUnretained({varName}).toOpaque(), {udName})\n");
            }
            else
            {
                sb.Append($"                {cbName}?(Unmanaged.passRetained({varName}).toOpaque(), {udName})\n");
            }
        }
        else if (branchParam.Kind == BridgeParameterKind.BoundStruct)
        {
            if (branchParam.IsObjCBridgeable)
            {
                // ObjC-bridgeable struct (e.g. Data → NSData, URL → NSURL) crosses the ABI as
                // an ObjC object pointer. `value as AnyObject` materializes a *bridged temporary*
                // distinct from the Swift `value` case binding — the binding keeps the Swift value
                // alive, NOT the bridged object. Because `passUnretained(...).toOpaque()` yields
                // an untracked raw pointer, ARC may release that temporary before the (synchronous)
                // C# callback dereferences it → use-after-free. Bind the bridged object to a local
                // and hold it across the call with
                // withExtendedLifetime so it outlives the raw-pointer use.
                sb.Append($"                let {varName}Obj = {varName} as AnyObject\n");
                sb.Append($"                withExtendedLifetime({varName}Obj) {{\n");
                sb.Append($"                    {cbName}?(Unmanaged.passUnretained({varName}Obj).toOpaque(), {udName})\n");
                sb.Append($"                }}\n");
            }
            else
            {
                var typeName = branchParam.BridgeTypeName;
                // Guard against nil callback to avoid leaking heap-allocated BoundStruct values.
                // Same pattern as BuildComplexClosureViewInitArg's nil guard.
                sb.Append($"                guard {cbName} != nil else {{ return }}\n");
                sb.Append($"                let {varName}Ptr = UnsafeMutableRawPointer.allocate(byteCount: MemoryLayout<{typeName}>.size, alignment: MemoryLayout<{typeName}>.alignment)\n");
                if (branchParam.StructProjection == StructProjectionKind.FrozenWithMemory)
                {
                    // A frozen-with-memory struct is copied (InitializeWithCopy) by C#, not adopted,
                    // so the Swift source buffer must be deinitialized + deallocated after the
                    // synchronous callback returns — otherwise the buffer and its +1 heap-field
                    // retains leak. Control flow here is linear (no early return between the call and
                    // cleanup), so inline rather than defer. Non-frozen structs are adopted by C#'s
                    // SafeHandle and must NOT be freed here (double-free).
                    sb.Append($"                let {varName}Typed = {varName}Ptr.initializeMemory(as: {typeName}.self, repeating: {varName}, count: 1)\n");
                    sb.Append($"                {cbName}?({varName}Ptr, {udName})\n");
                    sb.Append($"                {varName}Typed.deinitialize(count: 1)\n");
                    sb.Append($"                {varName}Ptr.deallocate()\n");
                }
                else
                {
                    sb.Append($"                {varName}Ptr.initializeMemory(as: {typeName}.self, repeating: {varName}, count: 1)\n");
                    sb.Append($"                {cbName}?({varName}Ptr, {udName})\n");
                }
            }
        }
        else
        {
            // Primitive
            var conversion = branchParam.CSharpConversion != null ? $"{varName} {branchParam.CSharpConversion}" : varName;
            sb.Append($"                {cbName}?({conversion}, {udName})\n");
        }

        return sb.ToString();
    }

    private static string GetInitDescription(ViewBridgeInfo info)
    {
        if (info.Constructors.Count == 0)
            return "init()";

        var ctor = info.Constructors[0];
        var paramDescs = new List<string>();
        for (int i = 1; i < ctor.CSSignature.Count; i++)
        {
            var param = ctor.CSSignature[i];
            paramDescs.Add($"{param.Name}: {param.SwiftTypeSpec}");
        }

        return paramDescs.Count == 0 ? "init()" : $"init({string.Join(", ", paramDescs)})";
    }

    private static string GetInitParamSummary(ViewBridgeInfo info)
    {
        if (info.UnsupportedReason != null)
            return info.UnsupportedReason;

        if (info.Constructors.Count == 0)
            return "no parameters";

        var ctor = info.Constructors[0];
        var paramDescs = new List<string>();
        for (int i = 1; i < ctor.CSSignature.Count; i++)
        {
            var param = ctor.CSSignature[i];
            paramDescs.Add($"{param.Name}: {param.SwiftTypeSpec}");
        }

        return paramDescs.Count == 0 ? "no parameters" : string.Join(", ", paramDescs);
    }

    #endregion
}

/// <summary>
/// Classification of a View's init for bridge generation.
/// </summary>
public enum ViewInitClassification
{
    Simple,
    AsyncDependency,
    Unsupported,
    /// <summary>Bridge hints say skip this view entirely — no bridge output generated.</summary>
    Skipped,
}

/// <summary>
/// Information about a detected SwiftUI View for bridge generation.
/// </summary>
public record ViewBridgeInfo(
    string ViewName,
    string ModuleName,
    ViewInitClassification Classification,
    string? UnsupportedReason,
    List<MethodDecl> Constructors,
    AsyncViewPattern? InferredPattern = null,
    GenericViewAnalysis? GenericAnalysis = null,
    List<BridgeModifier>? Modifiers = null);

/// <summary>
/// Strategy for filling generic View placeholder type parameters.
/// </summary>
public enum PlaceholderStrategy { Empty, UIView, AnyViewFromVC }

/// <summary>
/// Analysis result for a generic SwiftUI View type.
/// When IsBridgeable is true, ConcreteTypeArgs maps each generic parameter to its concrete substitution.
/// </summary>
public record GenericViewAnalysis(
    bool IsBridgeable,
    Dictionary<string, string> ConcreteTypeArgs,
    PlaceholderStrategy Strategy,
    int SelectedConstructorIndex,
    string? UnsupportedReason = null,
    HashSet<string>? NonViewResolvedParams = null);
