    #region C# Generation

    private static string GenerateCSharpBridge(
        string @namespace,
        string moduleName,
        List<(ViewBridgeInfo Info, List<BridgeParameter>? Params, AsyncViewPattern? AsyncPattern, bool IsFunctional, List<SynthesizedInitArg>? SynthesizedArgs, List<BridgeModifier>? Modifiers)> bridgeResults,
        ModuleEmissionContext? emissionContext)
    {
        var sb = new StringBuilder();
        bool hasFunctionalBridge = bridgeResults.Any(r => r.IsFunctional);

        if (hasFunctionalBridge)
        {
            sb.AppendLine("// Auto-generated by SwiftBindings — SwiftUI Bridge");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Runtime.CompilerServices;");
            sb.AppendLine("using System.Runtime.InteropServices;");
            sb.AppendLine("using System.Text;");
            sb.AppendLine("using System.Threading.Tasks;");

            // Add Swift.Runtime.InteropServices when class/struct closure args need SwiftMarshal
            bool hasClassClosureArgs = bridgeResults.Any(r => r.IsFunctional && r.Params != null &&
                r.Params.Any(p => p.Kind == BridgeParameterKind.TypedClosure &&
                    p.ClosureArguments != null &&
                    p.ClosureArguments.Any(a => a.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)));
            if (hasClassClosureArgs)
                sb.AppendLine("using Swift.Runtime.InteropServices;");
            // Add Swift.Runtime when class closure returns need Arc.Retain
            bool hasClassClosureReturns = bridgeResults.Any(r => r.IsFunctional && r.Params != null &&
                r.Params.Any(p => p.Kind == BridgeParameterKind.TypedClosure &&
                    p.ClosureReturn != null &&
                    p.ClosureReturn.Kind == BridgeParameterKind.BoundType));
            if (hasClassClosureReturns)
                sb.AppendLine("using Swift.Runtime;");
            sb.AppendLine();
            sb.AppendLine($"namespace {@namespace}");
            sb.AppendLine("{");

            // The session classes + NativeMethods P/Invokes target Swift @_cdecl symbols
            // that only exist on UIKit-family platforms (the Swift bridge file is now
            // `#if canImport(UIKit)` gated, leaving native macOS with no symbols to
            // resolve). Without this matching C# gate, consumers on macOS would compile
            // against the session API and hit DllNotFoundException at runtime when they
            // first call Create. Mirrors the per-property gate in
            // EmitTypedViewControllerAccessor.
            sb.AppendLine("#if __IOS__ || __TVOS__ || __MACCATALYST__");

            bool hasFunctionalViewWithGCHandles = bridgeResults.Any(r => r.IsFunctional);
            if (hasFunctionalViewWithGCHandles)
            {
                EmitSimpleViewPostReleaseHelpers(sb);
            }

            foreach (var (info, bridgeParams, asyncPattern, isFunctional, synthesizedArgs, modifiers) in bridgeResults)
            {
                if (isFunctional && asyncPattern != null)
                {
                    EmitAsyncCSharpBridge(sb, moduleName, info, asyncPattern, emissionContext);
                }
                else if (isFunctional)
                {
                    EmitFunctionalCSharpBridge(sb, moduleName, info, bridgeParams!, modifiers, emissionContext);
                }
                else
                {
                    EmitCSharpTemplate(sb, info);
                }
            }

            sb.AppendLine("#endif // __IOS__ || __TVOS__ || __MACCATALYST__");
            sb.AppendLine("}");
        }
        else
        {
            sb.AppendLine("// Auto-generated by SwiftBindings — SwiftUI Bridge Templates");
            sb.AppendLine("// These templates require manual completion before use.");
            sb.AppendLine("//");
            sb.AppendLine("// Views detected:");
            foreach (var (info, _, _, _, _, _) in bridgeResults)
            {
                var paramSummary = GetInitParamSummary(info);
                sb.AppendLine($"//   - {info.ViewName} ({info.Classification}: {paramSummary})");
            }
            sb.AppendLine("//");
        }

        sb.AppendLine();

        return sb.ToString();
    }

    // Shared post-release helper invoked from Swift after Unmanaged.release runs.
    // Lives once per bridge file so the function pointer is stable across all
    // simple-view session classes in the module.
    private static void EmitSimpleViewPostReleaseHelpers(StringBuilder sb)
    {
        sb.AppendLine("    internal static unsafe class SwiftUIBridgePostReleaseHelpers");
        sb.AppendLine("    {");
        sb.AppendLine("        [UnmanagedCallersOnly(CallConvs = new[] { typeof(global::System.Runtime.CompilerServices.CallConvCdecl) })]");
        sb.AppendLine("        internal static void FreeGCHandles(IntPtr buffer, int count)");
        sb.AppendLine("        {");
        OpenUcoFailFastGuard(sb);
        sb.AppendLine("            if (buffer == IntPtr.Zero) return;");
        sb.AppendLine("            var slots = (IntPtr*)buffer;");
        sb.AppendLine("            for (int i = 0; i < count; i++)");
        sb.AppendLine("            {");
        sb.AppendLine("                var raw = slots[i];");
        sb.AppendLine("                if (raw == IntPtr.Zero) continue;");
        sb.AppendLine("                var h = GCHandle.FromIntPtr(raw);");
        sb.AppendLine("                if (h.IsAllocated) h.Free();");
        sb.AppendLine("            }");
        sb.AppendLine("            NativeMemory.Free((void*)buffer);");
        CloseUcoFailFastGuard(sb);
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitFunctionalCSharpBridge(
        StringBuilder sb, string moduleName, ViewBridgeInfo info, List<BridgeParameter> bridgeParams,
        List<BridgeModifier>? modifiers = null,
        ModuleEmissionContext? emissionContext = null)
    {
        var prefix = $"SBW_{moduleName}_{info.ViewName}";
        var bridgeLib = $"{moduleName}Bridge";
        var hasClosures = bridgeParams.Any(p => p.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure or BridgeParameterKind.ResultClosure);
        var hasStrings = bridgeParams.Any(p => p.Kind == BridgeParameterKind.String ||
            (p.Kind == BridgeParameterKind.OptionalWrapped && p.InnerParameter?.Kind == BridgeParameterKind.String));
        var hasCodableBindings = bridgeParams.Any(p => p.IsBindingCodableStruct);
        var hasModifiers = modifiers != null && modifiers.Count > 0;
        var needsUnsafe = hasClosures || hasStrings || hasCodableBindings;

        // NativeMethods class
        sb.AppendLine($"    internal static partial class {info.ViewName}BridgeNativeMethods");
        sb.AppendLine("    {");
        sb.AppendLine($"        private const string BridgeLib = \"{bridgeLib}\";");
        sb.AppendLine();

        // Create P/Invoke — build params first
        var createPInvokeParams = new List<string>();
        foreach (var param in bridgeParams)
        {
            if (param.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure)
            {
                createPInvokeParams.Add($"IntPtr {param.Name}Callback");
                createPInvokeParams.Add($"IntPtr {param.Name}UserData");
            }
            else if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                createPInvokeParams.Add($"IntPtr {param.Name}SuccessCallback");
                createPInvokeParams.Add($"IntPtr {param.Name}SuccessUserData");
                createPInvokeParams.Add($"IntPtr {param.Name}ErrorCallback");
                createPInvokeParams.Add($"IntPtr {param.Name}ErrorUserData");
            }
            else if (param.Kind == BridgeParameterKind.String)
            {
                createPInvokeParams.Add($"IntPtr {param.Name}Ptr");
                createPInvokeParams.Add($"nint {param.Name}Len");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind == BridgeParameterKind.String)
            {
                createPInvokeParams.Add($"IntPtr {param.Name}Ptr");
                createPInvokeParams.Add($"nint {param.Name}Len");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                createPInvokeParams.Add($"IntPtr {param.CSharpName}");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped)
            {
                createPInvokeParams.Add($"int {param.Name}HasValue");
                createPInvokeParams.Add($"{param.InnerParameter!.CSharpPInvokeType} {param.Name}Value");
            }
            else if (param.IsBindingCodableStruct)
            {
                createPInvokeParams.Add($"IntPtr {param.Name}Ptr");
                createPInvokeParams.Add($"nint {param.Name}Len");
            }
            else if (param.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                createPInvokeParams.Add($"IntPtr {param.CSharpName}");
            }
            else if (param.Kind == BridgeParameterKind.BridgeArray)
            {
                createPInvokeParams.Add($"IntPtr {param.Name}Ptr");
                createPInvokeParams.Add($"int {param.Name}Count");
            }
            else
            {
                createPInvokeParams.Add($"{param.CSharpPInvokeType} {param.CSharpName}");
            }
        }
        foreach (var line in PInvokeEmitHelper.FormatDeclarationLines(new PInvokeEmissionInfo
        {
            LibraryPath = bridgeLib,
            EntryPoint = $"{prefix}_Create",
            MethodName = "Create",
            ReturnType = "IntPtr",
            ParametersString = string.Join(", ", createPInvokeParams),
            CallingConvention = PInvokeCallingConvention.Cdecl,
            Visibility = PInvokeVisibility.Internal,
            EmissionContext = emissionContext,
            EnforceWrapperContract = true
        }))
            sb.AppendLine($"        {line}");
        sb.AppendLine();

        // GetViewController P/Invoke
        foreach (var line in PInvokeEmitHelper.FormatDeclarationLines(new PInvokeEmissionInfo
        {
            LibraryPath = bridgeLib,
            EntryPoint = $"{prefix}_GetViewController",
            MethodName = "GetViewController",
            ReturnType = "IntPtr",
            ParametersString = "IntPtr handle",
            CallingConvention = PInvokeCallingConvention.Cdecl,
            Visibility = PInvokeVisibility.Internal,
            EmissionContext = emissionContext,
            EnforceWrapperContract = true
        }))
            sb.AppendLine($"        {line}");
        sb.AppendLine();

        // Free P/Invoke — see Swift _Free comment for handle-buffer ownership rules.
        foreach (var line in PInvokeEmitHelper.FormatDeclarationLines(new PInvokeEmissionInfo
        {
            LibraryPath = bridgeLib,
            EntryPoint = $"{prefix}_Free",
            MethodName = "Free",
            ReturnType = "void",
            ParametersString = "IntPtr handle, IntPtr handleBuffer, int handleCount, IntPtr postReleaseFreeFn",
            CallingConvention = PInvokeCallingConvention.Cdecl,
            Visibility = PInvokeVisibility.Internal,
            EmissionContext = emissionContext,
            EnforceWrapperContract = true
        }))
            sb.AppendLine($"        {line}");

        // Update P/Invoke declarations for updatable params
        EmitCSharpUpdatePInvokeDeclarations(sb, prefix, bridgeLib, bridgeParams, emissionContext);

        // Read+Free P/Invoke declarations for Binding<Codable> params
        var codableBindingParamsDecl = bridgeParams.Where(p => p.IsBindingCodableStruct).ToList();
        if (codableBindingParamsDecl.Count > 0)
            EmitCSharpReadPInvokeDeclarations(sb, prefix, bridgeLib, codableBindingParamsDecl, emissionContext);

        // Modifier Set P/Invoke declarations
        if (hasModifiers)
            EmitCSharpModifierPInvokeDeclarations(sb, prefix, bridgeLib, modifiers!, emissionContext);

        // Lifecycle P/Invoke declaration.
        EmitCSharpLifecyclePInvoke(sb, prefix, bridgeLib, emissionContext);

        // Universal modifier P/Invoke declarations — skip collisions with view-specific modifiers.
        var csharpModifierSetNames = modifiers?.Select(m => $"Set{m.PascalName}").ToHashSet() ?? new HashSet<string>();
        EmitCSharpUniversalModifierPInvokes(sb, prefix, bridgeLib, csharpModifierSetNames, emissionContext);

        // Presentation P/Invoke declarations.
        EmitCSharpPresentationPInvokes(sb, prefix, bridgeLib, emissionContext);

        sb.AppendLine("    }");
        sb.AppendLine();

        // Session class
        sb.AppendLine($"    public sealed class {info.ViewName}Session : IDisposable");
        sb.AppendLine("    {");
        sb.AppendLine("        private IntPtr _handle;");
        sb.AppendLine("        private bool _disposed;");
        if (hasClosures)
        {
            sb.AppendLine("        private GCHandle[] _closureHandles = Array.Empty<GCHandle>();");
        }
        // Lifecycle handles (always present)
        sb.AppendLine("        private GCHandle[] _lifecycleHandles = Array.Empty<GCHandle>();");
        var hasUpdatableParams = bridgeParams.Any(p => p.IsUpdatable);
        if (hasUpdatableParams)
        {
            sb.AppendLine("        private System.ComponentModel.INotifyPropertyChanged? _boundViewModel;");
            sb.AppendLine("        private System.Collections.Generic.Dictionary<string, Action>? _propertyDispatchers;");
        }
        sb.AppendLine();
        sb.AppendLine($"        internal {info.ViewName}Session(IntPtr handle) => _handle = handle;");
        sb.AppendLine();
        sb.AppendLine("        public IntPtr Handle => !_disposed");
        sb.AppendLine($"            ? _handle");
        sb.AppendLine($"            : throw new ObjectDisposedException(nameof({info.ViewName}Session));");
        sb.AppendLine();
        sb.AppendLine("        public IntPtr GetViewController() =>");
        sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.GetViewController(Handle);");
        sb.AppendLine();
        EmitTypedViewControllerAccessor(sb);

        // Trampolines for closure parameters
        foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.VoidClosure))
        {
            var trampolineName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..] + "Trampoline";
            sb.AppendLine($"        [UnmanagedCallersOnly(CallConvs = new[] {{ typeof(global::System.Runtime.CompilerServices.CallConvCdecl) }})]");
            sb.AppendLine($"        private static void {trampolineName}(IntPtr userData)");
            sb.AppendLine("        {");
            OpenUcoFailFastGuard(sb);
            sb.AppendLine("            if (userData != IntPtr.Zero)");
            sb.AppendLine("            {");
            sb.AppendLine("                var h = GCHandle.FromIntPtr(userData);");
            sb.AppendLine("                if (h.Target is Action action)");
            sb.AppendLine("                    action();");
            sb.AppendLine("            }");
            CloseUcoFailFastGuard(sb);
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        // Typed closure trampolines
        foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.TypedClosure))
        {
            EmitTypedClosureTrampoline(sb, param);
        }

        // Result closure trampolines (two per ResultClosure: success + error)
        foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.ResultClosure))
        {
            var successTrampolineName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..] + "SuccessTrampoline";
            var errorTrampolineName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..] + "ErrorTrampoline";
            EmitResultBranchTrampoline(sb, successTrampolineName, param.ResultSuccessParam!);
            EmitResultBranchTrampoline(sb, errorTrampolineName, param.ResultErrorParam!);
        }

        // Lifecycle trampolines.
        EmitCSharpLifecycleTrampolines(sb);

        // Create factory method
        EmitSimpleCreateFactory(sb, info, bridgeParams, needsUnsafe, hasClosures, hasStrings);

        // Update methods for updatable params
        EmitCSharpUpdateMethods(sb, info, bridgeParams);

        // Read methods for Binding<Codable> params
        var codableBindingParamsMethods = bridgeParams.Where(p => p.IsBindingCodableStruct).ToList();
        if (codableBindingParamsMethods.Count > 0)
            EmitCSharpReadMethods(sb, info, codableBindingParamsMethods);

        // Observable binding methods.
        if (hasUpdatableParams)
            EmitCSharpObservableBindingMethods(sb, info, bridgeParams);

        // Modifier methods
        if (hasModifiers)
            EmitCSharpModifierMethods(sb, info, modifiers!);

        // Lifecycle method.
        EmitCSharpLifecycleMethod(sb, info);

        // Universal modifier methods — skip collisions with view-specific modifiers.
        EmitCSharpUniversalModifierMethods(sb, info, csharpModifierSetNames);

        // Presentation methods.
        EmitCSharpPresentationMethods(sb, info);

        // Dispose pattern with finalizer: GC-driven cleanup is the only fallback when a
        // SwiftUI consumer constructs a session and stores it on a struct View without
        // a using/explicit-Dispose handshake. Without the finalizer, both the +1-retained
        // native session pointer and every pinned GCHandle leak permanently.
        sb.AppendLine("        public void Dispose()");
        sb.AppendLine("        {");
        sb.AppendLine("            Dispose(disposing: true);");
        sb.AppendLine("            GC.SuppressFinalize(this);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine($"        ~{info.ViewName}Session() => Dispose(disposing: false);");
        sb.AppendLine();
        // Dispose hands the GCHandle batch to the native Free callback. Swift owns
        // disposal so the handles outlive any Swift state captured via user-data
        // pointers — when Free dispatches async to main, those handles must remain
        // alive until Unmanaged.release runs.
        sb.AppendLine("        private unsafe void Dispose(bool disposing)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (_disposed) return;");
        if (hasUpdatableParams)
        {
            // Unbind() touches managed INotifyPropertyChanged subscriptions — only safe on
            // the disposing path. On finalize, the publisher may already be unreachable.
            sb.AppendLine("            if (disposing) Unbind();");
        }
        sb.AppendLine("            _disposed = true;");
        sb.AppendLine();
        sb.AppendLine("            int totalHandles = 0;");
        if (hasClosures)
        {
            sb.AppendLine("            foreach (var h in _closureHandles) if (h.IsAllocated) totalHandles++;");
        }
        sb.AppendLine("            foreach (var h in _lifecycleHandles) if (h.IsAllocated) totalHandles++;");
        sb.AppendLine();
        sb.AppendLine("            IntPtr handleBuffer = IntPtr.Zero;");
        sb.AppendLine("            IntPtr postReleaseFreeFn = IntPtr.Zero;");
        sb.AppendLine("            if (totalHandles > 0)");
        sb.AppendLine("            {");
        sb.AppendLine("                handleBuffer = (IntPtr)NativeMemory.Alloc((nuint)totalHandles, (nuint)sizeof(IntPtr));");
        sb.AppendLine("                var slots = (IntPtr*)handleBuffer;");
        sb.AppendLine("                int idx = 0;");
        if (hasClosures)
        {
            sb.AppendLine("                foreach (var h in _closureHandles)");
            sb.AppendLine("                    if (h.IsAllocated) slots[idx++] = GCHandle.ToIntPtr(h);");
        }
        sb.AppendLine("                foreach (var h in _lifecycleHandles)");
        sb.AppendLine("                    if (h.IsAllocated) slots[idx++] = GCHandle.ToIntPtr(h);");
        sb.AppendLine("                delegate* unmanaged[Cdecl]<IntPtr, int, void> fn = &SwiftUIBridgePostReleaseHelpers.FreeGCHandles;");
        sb.AppendLine("                postReleaseFreeFn = (IntPtr)fn;");
        sb.AppendLine("            }");
        sb.AppendLine();
        if (hasClosures)
        {
            sb.AppendLine("            _closureHandles = Array.Empty<GCHandle>();");
        }
        sb.AppendLine("            _lifecycleHandles = Array.Empty<GCHandle>();");
        sb.AppendLine($"            {info.ViewName}BridgeNativeMethods.Free(_handle, handleBuffer, totalHandles, postReleaseFreeFn);");
        sb.AppendLine("            _handle = IntPtr.Zero;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    /// <summary>
    /// Emits a typed <c>ViewController</c> property alongside the raw <c>GetViewController()</c>
    /// IntPtr accessor. The hosted view is a <c>UIHostingController</c> on UIKit-family platforms,
    /// so the property is gated to iOS/tvOS/Mac Catalyst (where <c>UIKit.UIViewController</c> exists)
    /// and absent on macOS. Swift hands back the controller via <c>passUnretained</c> (+0) — the Swift
    /// Session holds the only strong reference — and the C# side wraps it as a non-owning managed peer
    /// (<c>Runtime.GetNSObject</c>, <c>owns: false</c>), which does not extend the native lifetime. The
    /// controller therefore lives as long as the session, or — once embedded in a UIKit / .NET MAUI
    /// hierarchy whose parent retains it — independently of the session.
    /// </summary>
    private static void EmitTypedViewControllerAccessor(StringBuilder sb)
    {
        sb.AppendLine("#if __IOS__ || __TVOS__ || __MACCATALYST__");
        sb.AppendLine("        /// <summary>");
        sb.AppendLine("        /// The hosted SwiftUI view as a typed <see cref=\"global::UIKit.UIViewController\"/>, ready to embed");
        sb.AppendLine("        /// in a UIKit / .NET MAUI view hierarchy (e.g. <c>AddChildViewController</c> or as a page's native");
        sb.AppendLine("        /// controller). This is a non-owning managed peer over the native hosting controller; embedding it");
        sb.AppendLine("        /// transfers ownership to the parent (which retains it), so an embedded controller stays valid even");
        sb.AppendLine("        /// after this session is disposed. Until embedded (or otherwise retained), the controller lives only");
        sb.AppendLine("        /// as long as this session — do not use it after disposing an un-embedded session.");
        sb.AppendLine("        /// </summary>");
        sb.AppendLine("        public global::UIKit.UIViewController? ViewController =>");
        sb.AppendLine("            global::ObjCRuntime.Runtime.GetNSObject<global::UIKit.UIViewController>(GetViewController());");
        sb.AppendLine("#endif");
        sb.AppendLine();
    }

    private static void EmitSimpleCreateFactory(
        StringBuilder sb, ViewBridgeInfo info, List<BridgeParameter> bridgeParams,
        bool needsUnsafe, bool hasClosures, bool hasStrings)
    {
        var hasCodableBindings = bridgeParams.Any(p => p.IsBindingCodableStruct);
        // Factory parameter list (idiomatic C# types)
        // C# requires optional parameters after all required parameters.
        var requiredParams = new List<string>();
        var optionalParams = new List<string>();
        foreach (var param in bridgeParams)
        {
            // ResultClosure expands into two factory params: onSuccess + onError
            if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                var successCsharp = GetClosureArgCSharpType(param.ResultSuccessParam!);
                var errorCsharp = GetClosureArgCSharpType(param.ResultErrorParam!);
                optionalParams.Add($"Action<{successCsharp}>? {param.Name}Success = null");
                optionalParams.Add($"Action<{errorCsharp}>? {param.Name}Error = null");
                continue;
            }
            var type = GetFactoryParamType(param);
            var isOptionalString = param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind == BridgeParameterKind.String;
            var defaultVal = param.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure ? " = null"
                : param.Kind == BridgeParameterKind.String ? " = null"
                : isOptionalString ? " = null" : "";
            if (defaultVal.Length > 0)
                optionalParams.Add($"{type} {param.CSharpName}{defaultVal}");
            else
                requiredParams.Add($"{type} {param.CSharpName}");
        }
        requiredParams.AddRange(optionalParams);
        // Lifecycle callback params (always present, always optional).
        requiredParams.Add("Action? onAppear = null");
        requiredParams.Add("Action? onDisappear = null");

        // The Create factory hardcodes bookkeeping locals (handle/session/closureHandles
        // and the loop locals h/fn/i). A View whose init param projects to one of those names
        // would shadow the local → CS0136/CS0128 and the binding fails to compile. Reserve every
        // synthetic through a scope seeded with the factory's user-facing param identifiers so the
        // SYNTHETIC name is escaped (never the user's). No collision → original names → zero churn.
        var factoryUserNames = new List<string>();
        foreach (var param in bridgeParams)
        {
            if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                factoryUserNames.Add($"{param.Name}Success");
                factoryUserNames.Add($"{param.Name}Error");
            }
            else
            {
                factoryUserNames.Add(param.Name);
            }
        }
        factoryUserNames.Add("onAppear");
        factoryUserNames.Add("onDisappear");
        var factoryScope = new SyntheticNameScope(factoryUserNames);
        var handleLocal = factoryScope.Reserve("handle");
        var sessionLocal = factoryScope.Reserve("session");
        var closureHandlesLocal = factoryScope.Reserve("closureHandles");
        var hLocal = factoryScope.Reserve("h");
        var fnLocal = factoryScope.Reserve("fn");
        var iLocal = factoryScope.Reserve("i");

        var unsafeKeyword = needsUnsafe ? "unsafe " : "";
        var hasArrays = bridgeParams.Any(p => p.Kind == BridgeParameterKind.BridgeArray);
        sb.AppendLine($"        public static {unsafeKeyword}{info.ViewName}Session Create({string.Join(", ", requiredParams)})");
        sb.AppendLine("        {");

        if (hasClosures || hasArrays)
        {
            if (hasClosures)
                sb.AppendLine($"            var {closureHandlesLocal} = new global::System.Collections.Generic.List<GCHandle>();");
            // Declare array handle variables BEFORE try so they're visible in finally for cleanup.
            // The actual GCHandle.Alloc calls happen inside try to prevent leaks if a second alloc throws.
            if (hasArrays)
                EmitCSharpArrayHandleDeclarations(sb, bridgeParams, "            ");
            sb.AppendLine("            try");
            sb.AppendLine("            {");
            var indent = "                ";

            // Array pinning: extract raw values and pin for native call (inside try block)
            if (hasArrays)
                EmitCSharpArrayPinning(sb, bridgeParams, indent, iLocal);

            // Setup closure parameters
            foreach (var param in bridgeParams.Where(p => p.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure))
            {
                var trampolineName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..] + "Trampoline";
                sb.AppendLine($"{indent}IntPtr {param.Name}Callback = IntPtr.Zero;");
                sb.AppendLine($"{indent}IntPtr {param.Name}UserData = IntPtr.Zero;");
                sb.AppendLine($"{indent}if ({param.CSharpName} != null)");
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    var {hLocal} = GCHandle.Alloc({param.CSharpName});");
                sb.AppendLine($"{indent}    {closureHandlesLocal}.Add({hLocal});");
                sb.AppendLine($"{indent}    {param.Name}UserData = GCHandle.ToIntPtr({hLocal});");

                // Build delegate* type matching trampoline signature
                var fnPtrType = GetClosureFunctionPointerType(param);
                sb.AppendLine($"{indent}    {fnPtrType} {fnLocal} = &{trampolineName};");
                sb.AppendLine($"{indent}    {param.Name}Callback = (IntPtr){fnLocal};");
                sb.AppendLine($"{indent}}}");
                sb.AppendLine();
            }

            // Setup ResultClosure parameters (two callbacks per param: success + error)
            foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.ResultClosure))
            {
                foreach (var branch in new[] { "Success", "Error" })
                {
                    var branchParam = branch == "Success" ? param.ResultSuccessParam! : param.ResultErrorParam!;
                    var factoryName = $"{param.CSharpName}{branch}";
                    var trampolineName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..] + $"{branch}Trampoline";
                    sb.AppendLine($"{indent}IntPtr {factoryName}Callback = IntPtr.Zero;");
                    sb.AppendLine($"{indent}IntPtr {factoryName}UserData = IntPtr.Zero;");
                    sb.AppendLine($"{indent}if ({factoryName} != null)");
                    sb.AppendLine($"{indent}{{");
                    sb.AppendLine($"{indent}    var {hLocal} = GCHandle.Alloc({factoryName});");
                    sb.AppendLine($"{indent}    {closureHandlesLocal}.Add({hLocal});");
                    sb.AppendLine($"{indent}    {factoryName}UserData = GCHandle.ToIntPtr({hLocal});");
                    var fnPtrType = BuildResultBranchFnPtrType(branchParam);
                    sb.AppendLine($"{indent}    {fnPtrType} {fnLocal} = &{trampolineName};");
                    sb.AppendLine($"{indent}    {factoryName}Callback = (IntPtr){fnLocal};");
                    sb.AppendLine($"{indent}}}");
                    sb.AppendLine();
                }
            }

            // String encoding (includes Optional<String> params)
            foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.String))
            {
                sb.AppendLine($"{indent}var {param.Name}Bytes = Encoding.UTF8.GetBytes({param.CSharpName} ?? \"\");");
            }
            foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.OptionalWrapped && p.InnerParameter?.Kind == BridgeParameterKind.String))
            {
                sb.AppendLine($"{indent}byte[]? {param.Name}Bytes = {param.CSharpName} != null ? Encoding.UTF8.GetBytes({param.CSharpName}) : null;");
            }
            // Binding<Codable> JSON encoding
            foreach (var param in bridgeParams.Where(p => p.IsBindingCodableStruct))
            {
                sb.AppendLine($"{indent}ArgumentNullException.ThrowIfNull({param.CSharpName});");
                sb.AppendLine($"{indent}var {param.Name}Bytes = {param.CSharpName}.EncodeToJson();");
            }

            // Call with fixed block if strings or Codable bindings present
            EmitSimpleCreateCall(sb, info, bridgeParams, hasStrings, hasClosures, indent, handleLocal, sessionLocal, closureHandlesLocal);

            sb.AppendLine("            }");
            sb.AppendLine("            finally");
            sb.AppendLine("            {");
            if (hasClosures)
            {
                sb.AppendLine($"                foreach (var {hLocal} in {closureHandlesLocal})");
                sb.AppendLine($"                    if ({hLocal}.IsAllocated) {hLocal}.Free();");
            }
            if (hasArrays)
                EmitCSharpArrayCleanup(sb, bridgeParams, "                ");
            sb.AppendLine("            }");
        }
        else if (hasStrings || hasCodableBindings)
        {
            var indent = "            ";
            // String encoding (includes Optional<String> params)
            foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.String))
            {
                sb.AppendLine($"{indent}var {param.Name}Bytes = Encoding.UTF8.GetBytes({param.CSharpName} ?? \"\");");
            }
            foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.OptionalWrapped && p.InnerParameter?.Kind == BridgeParameterKind.String))
            {
                sb.AppendLine($"{indent}byte[]? {param.Name}Bytes = {param.CSharpName} != null ? Encoding.UTF8.GetBytes({param.CSharpName}) : null;");
            }
            // Binding<Codable> JSON encoding
            foreach (var param in bridgeParams.Where(p => p.IsBindingCodableStruct))
            {
                sb.AppendLine($"{indent}ArgumentNullException.ThrowIfNull({param.CSharpName});");
                sb.AppendLine($"{indent}var {param.Name}Bytes = {param.CSharpName}.EncodeToJson();");
            }
            EmitSimpleCreateCall(sb, info, bridgeParams, hasStrings, hasClosures, indent, handleLocal, sessionLocal, closureHandlesLocal);
        }
        else
        {
            // Simple case: no closures, no strings, no arrays
            var nativeArgs = BuildSimpleNativeCallArgs(bridgeParams);
            sb.AppendLine($"            var {handleLocal} = {info.ViewName}BridgeNativeMethods.Create({string.Join(", ", nativeArgs)});");
            sb.AppendLine($"            if ({handleLocal} == IntPtr.Zero)");
            sb.AppendLine($"                throw new InvalidOperationException(\"Failed to create {info.ViewName} session.\");");
            sb.AppendLine($"            var {sessionLocal} = new {info.ViewName}Session({handleLocal});");
            sb.AppendLine($"            {sessionLocal}.SetLifecycleCallbacks(onAppear, onDisappear);");
            sb.AppendLine($"            return {sessionLocal};");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
    }

    /// <summary>
    /// Emits variable declarations for array GCHandles and pinned pointers.
    /// These must be declared before the try block so they're visible in the finally block for cleanup.
    /// </summary>
    private static void EmitCSharpArrayHandleDeclarations(StringBuilder sb, List<BridgeParameter> bridgeParams, string indent)
    {
        foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.BridgeArray))
        {
            sb.AppendLine($"{indent}var {param.Name}Handle = default(GCHandle);");
            sb.AppendLine($"{indent}IntPtr {param.Name}PinnedPtr = IntPtr.Zero;");
        }
    }

    /// <summary>
    /// Emits C# array pinning: extracts raw values from element arrays and pins via GCHandle.
    /// Must be called inside a try block (handle declarations emitted separately by EmitCSharpArrayHandleDeclarations).
    /// </summary>
    private static void EmitCSharpArrayPinning(StringBuilder sb, List<BridgeParameter> bridgeParams, string indent, string iLocal)
    {
        foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.BridgeArray))
        {
            var inner = param.InnerParameter!;
            var rawArrayType = inner.CSharpPInvokeType;

            if (inner.Kind == BridgeParameterKind.BoundEnum)
            {
                // Extract raw values from enum array
                sb.AppendLine($"{indent}if ({param.CSharpName} != null && {param.CSharpName}.Length > 0)");
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    var {param.Name}Raw = new {rawArrayType}[{param.CSharpName}.Length];");
                sb.AppendLine($"{indent}    for (int {iLocal} = 0; {iLocal} < {param.CSharpName}.Length; {iLocal}++)");
                if (inner.IsSimpleEnum)
                    sb.AppendLine($"{indent}        {param.Name}Raw[{iLocal}] = ({rawArrayType}){param.CSharpName}[{iLocal}];");
                else
                    sb.AppendLine($"{indent}        {param.Name}Raw[{iLocal}] = {param.CSharpName}[{iLocal}].RawValue;");
                sb.AppendLine($"{indent}    {param.Name}Handle = GCHandle.Alloc({param.Name}Raw, GCHandleType.Pinned);");
                sb.AppendLine($"{indent}    {param.Name}PinnedPtr = {param.Name}Handle.AddrOfPinnedObject();");
                sb.AppendLine($"{indent}}}");
            }
            else if (inner.Kind == BridgeParameterKind.Primitive && inner.CSharpConversion != null)
            {
                // Bool array: convert to int array
                sb.AppendLine($"{indent}if ({param.CSharpName} != null && {param.CSharpName}.Length > 0)");
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    var {param.Name}Raw = new int[{param.CSharpName}.Length];");
                sb.AppendLine($"{indent}    for (int {iLocal} = 0; {iLocal} < {param.CSharpName}.Length; {iLocal}++)");
                sb.AppendLine($"{indent}        {param.Name}Raw[{iLocal}] = {param.CSharpName}[{iLocal}] {inner.CSharpConversion};");
                sb.AppendLine($"{indent}    {param.Name}Handle = GCHandle.Alloc({param.Name}Raw, GCHandleType.Pinned);");
                sb.AppendLine($"{indent}    {param.Name}PinnedPtr = {param.Name}Handle.AddrOfPinnedObject();");
                sb.AppendLine($"{indent}}}");
            }
            else
            {
                // Primitive array: pin directly
                sb.AppendLine($"{indent}if ({param.CSharpName} != null && {param.CSharpName}.Length > 0)");
                sb.AppendLine($"{indent}{{");
                sb.AppendLine($"{indent}    {param.Name}Handle = GCHandle.Alloc({param.CSharpName}, GCHandleType.Pinned);");
                sb.AppendLine($"{indent}    {param.Name}PinnedPtr = {param.Name}Handle.AddrOfPinnedObject();");
                sb.AppendLine($"{indent}}}");
            }
        }
    }

    /// <summary>
    /// Emits GCHandle cleanup for pinned arrays in a finally block.
    /// </summary>
    private static void EmitCSharpArrayCleanup(StringBuilder sb, List<BridgeParameter> bridgeParams, string indent)
    {
        foreach (var param in bridgeParams.Where(p => p.Kind == BridgeParameterKind.BridgeArray))
        {
            sb.AppendLine($"{indent}if ({param.Name}Handle.IsAllocated) {param.Name}Handle.Free();");
        }
    }

    private static void EmitSimpleCreateCall(
        StringBuilder sb, ViewBridgeInfo info, List<BridgeParameter> bridgeParams,
        bool hasStrings, bool hasClosures, string indent,
        string handleLocal, string sessionLocal, string closureHandlesLocal)
    {
        var pinnedParams = bridgeParams.Where(p => p.Kind == BridgeParameterKind.String ||
            (p.Kind == BridgeParameterKind.OptionalWrapped && p.InnerParameter?.Kind == BridgeParameterKind.String) ||
            p.IsBindingCodableStruct).ToList();
        var nativeArgs = BuildSimpleNativeCallArgs(bridgeParams);
        var needsFixed = pinnedParams.Count > 0;

        if (needsFixed)
        {
            var fixedDecls = "byte* " + string.Join(", ", pinnedParams.Select(p => $"{p.Name}Ptr = {p.Name}Bytes"));
            sb.AppendLine($"{indent}fixed ({fixedDecls})");
            sb.AppendLine($"{indent}{{");
            var innerIndent = indent + "    ";
            sb.AppendLine($"{innerIndent}var {handleLocal} = {info.ViewName}BridgeNativeMethods.Create({string.Join(", ", nativeArgs)});");
            sb.AppendLine($"{innerIndent}if ({handleLocal} == IntPtr.Zero)");
            sb.AppendLine($"{innerIndent}    throw new InvalidOperationException(\"Failed to create {info.ViewName} session.\");");
            sb.AppendLine($"{innerIndent}var {sessionLocal} = new {info.ViewName}Session({handleLocal});");
            if (hasClosures)
            {
                sb.AppendLine($"{innerIndent}{sessionLocal}._closureHandles = {closureHandlesLocal}.ToArray();");
                sb.AppendLine($"{innerIndent}{closureHandlesLocal}.Clear();");
            }
            sb.AppendLine($"{innerIndent}{sessionLocal}.SetLifecycleCallbacks(onAppear, onDisappear);");
            sb.AppendLine($"{innerIndent}return {sessionLocal};");
            sb.AppendLine($"{indent}}}");
        }
        else
        {
            sb.AppendLine($"{indent}var {handleLocal} = {info.ViewName}BridgeNativeMethods.Create({string.Join(", ", nativeArgs)});");
            sb.AppendLine($"{indent}if ({handleLocal} == IntPtr.Zero)");
            sb.AppendLine($"{indent}    throw new InvalidOperationException(\"Failed to create {info.ViewName} session.\");");
            sb.AppendLine($"{indent}var {sessionLocal} = new {info.ViewName}Session({handleLocal});");
            if (hasClosures)
            {
                sb.AppendLine($"{indent}{sessionLocal}._closureHandles = {closureHandlesLocal}.ToArray();");
                sb.AppendLine($"{indent}{closureHandlesLocal}.Clear();");
            }
            sb.AppendLine($"{indent}{sessionLocal}.SetLifecycleCallbacks(onAppear, onDisappear);");
            sb.AppendLine($"{indent}return {sessionLocal};");
        }
    }

    private static List<string> BuildSimpleNativeCallArgs(List<BridgeParameter> bridgeParams)
    {
        var args = new List<string>();
        foreach (var param in bridgeParams)
        {
            if (param.Kind is BridgeParameterKind.VoidClosure or BridgeParameterKind.TypedClosure)
            {
                args.Add($"{param.Name}Callback");
                args.Add($"{param.Name}UserData");
            }
            else if (param.Kind == BridgeParameterKind.ResultClosure)
            {
                args.Add($"{param.Name}SuccessCallback");
                args.Add($"{param.Name}SuccessUserData");
                args.Add($"{param.Name}ErrorCallback");
                args.Add($"{param.Name}ErrorUserData");
            }
            else if (param.Kind == BridgeParameterKind.String)
            {
                args.Add($"(IntPtr){param.Name}Ptr");
                args.Add($"{param.Name}Bytes.Length");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind == BridgeParameterKind.String)
            {
                args.Add($"{param.CSharpName} == null ? IntPtr.Zero : (IntPtr){param.Name}Ptr");
                args.Add($"{param.Name}Bytes?.Length ?? 0");
            }
            else if (param.IsBindingCodableStruct)
            {
                args.Add($"(IntPtr){param.Name}Ptr");
                args.Add($"{param.Name}Bytes.Length");
            }
            else if (param.Kind == BridgeParameterKind.BoundEnum)
            {
                if (param.IsSimpleEnum)
                {
                    // Simple enums are C# enum value types — cast to underlying int
                    args.Add($"({param.CSharpPInvokeType}){param.CSharpName}");
                }
                else
                {
                    // Complex enums are C# classes with .RawValue property
                    args.Add($"{param.CSharpName}.RawValue");
                }
            }
            else if (param.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                args.Add(param.IsObjCBridgeable ? $"{param.CSharpName}.Handle" : $"{param.CSharpName}.Payload.DangerousGetHandle()");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped && param.InnerParameter?.Kind is BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct)
            {
                var innerBridgeable = param.InnerParameter?.IsObjCBridgeable == true;
                args.Add(innerBridgeable ? $"{param.CSharpName}?.Handle ?? IntPtr.Zero" : $"{param.CSharpName}?.Payload.DangerousGetHandle() ?? IntPtr.Zero");
            }
            else if (param.Kind == BridgeParameterKind.OptionalWrapped)
            {
                var inner = param.InnerParameter!;
                if (inner.Kind == BridgeParameterKind.BoundEnum)
                {
                    if (inner.IsSimpleEnum)
                    {
                        // Simple enum is a C# value type — use .HasValue, cast to int
                        args.Add($"{param.CSharpName}.HasValue ? 1 : 0");
                        args.Add($"{param.CSharpName}.HasValue ? ({inner.CSharpPInvokeType}){param.CSharpName}.Value : 0");
                    }
                    else
                    {
                        // Complex enum is a reference type (class) — use != null, .RawValue
                        args.Add($"{param.CSharpName} != null ? 1 : 0");
                        args.Add($"{param.CSharpName}?.RawValue ?? 0");
                    }
                }
                else if (inner.CSharpConversion != null) // Bool
                {
                    args.Add($"{param.CSharpName}.HasValue ? 1 : 0");
                    args.Add($"{param.CSharpName}.HasValue ? ({param.CSharpName}.Value {inner.CSharpConversion}) : 0");
                }
                else
                {
                    args.Add($"{param.CSharpName}.HasValue ? 1 : 0");
                    args.Add($"{param.CSharpName} ?? 0");
                }
            }
            else if (param.Kind == BridgeParameterKind.BridgeArray)
            {
                args.Add($"{param.Name}PinnedPtr");
                args.Add($"{param.CSharpName}?.Length ?? 0");
            }
            else if (param.CSharpConversion != null)
            {
                // Bool: value ? 1 : 0
                args.Add($"{param.CSharpName} {param.CSharpConversion}");
            }
            else
            {
                // Pass the C#-safe operand (CSharpName), consistent with every sibling branch.
                // A C#-keyword param name must be `@`-escaped at the call site (`@event`), or the
                // emitted native call `Create(event, …)` is invalid C#.
                args.Add(param.CSharpName);
            }
        }
        return args;
    }

