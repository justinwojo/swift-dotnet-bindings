    /// <summary>
    /// Returns the Swift type for UIHostingController, with concrete type args for generic views.
    /// When the view has updatable (non-closure) params or modifiers, returns the Wrapper type instead.
    /// </summary>
    internal static string GetSwiftHostedViewType(ViewBridgeInfo info, List<BridgeParameter>? bridgeParams = null,
        List<BridgeModifier>? modifiers = null)
    {
        // If there are updatable params or modifiers, the hosted view is the Wrapper, not the raw view
        if (bridgeParams != null && bridgeParams.Any(p => p.IsUpdatable))
        {
            var prefix = $"SBW_{info.ModuleName}_{info.ViewName}";
            return $"{prefix}_Wrapper";
        }
        if (modifiers != null && modifiers.Count > 0)
        {
            var prefix = $"SBW_{info.ModuleName}_{info.ViewName}";
            return $"{prefix}_Wrapper";
        }

        if (info.GenericAnalysis == null)
            return info.ViewName;

        return $"{info.ViewName}<{GetOrderedTypeArgs(info.GenericAnalysis)}>";
    }

    /// <summary>
    /// Returns the raw view type with concrete generic args (not the Wrapper type).
    /// Used for applyModifiers helper parameter/return type.
    /// </summary>
    internal static string GetConcreteViewType(ViewBridgeInfo info)
    {
        if (info.GenericAnalysis == null)
            return info.ViewName;

        return $"{info.ViewName}<{GetOrderedTypeArgs(info.GenericAnalysis)}>";
    }

    /// <summary>
    /// Returns the view name for use in Swift init calls.
    /// Uses explicit type args when non-View resolved generic params are present,
    /// since Swift cannot infer type args from bridged primitive/string params.
    /// For View-only generics, Swift infers from synthesized ViewBuilder closures.
    /// </summary>
    internal static string GetViewInitTypeName(ViewBridgeInfo info)
    {
        if (info.GenericAnalysis?.NonViewResolvedParams is { Count: > 0 })
        {
            return $"{info.ViewName}<{GetOrderedTypeArgs(info.GenericAnalysis)}>";
        }
        return info.ViewName;
    }

    /// <summary>
    /// Returns the concrete type args in declared generic parameter order.
    /// Keys are τ_0_0, τ_0_1, etc. Sorted by numeric suffix to handle 10+ params
    /// correctly (lexicographic sort would place τ_0_10 before τ_0_2).
    /// </summary>
    private static string GetOrderedTypeArgs(GenericViewAnalysis analysis)
    {
        return string.Join(", ", analysis.ConcreteTypeArgs
            .OrderBy(kv => ExtractGenericParamIndex(kv.Key))
            .Select(kv => kv.Value));
    }

    /// <summary>
    /// Extracts the trailing numeric index from a generic parameter key like "τ_0_2".
    /// Falls back to int.MaxValue if the key doesn't match the expected format.
    /// </summary>
    private static int ExtractGenericParamIndex(string key)
    {
        var lastUnderscore = key.LastIndexOf('_');
        if (lastUnderscore >= 0 && int.TryParse(key.AsSpan(lastUnderscore + 1), out var index))
            return index;
        return int.MaxValue;
    }

