    /// Returns the Swift type for a modifier parameter's state variable (used in Optional wrapping).
    /// </summary>
    private static string GetModifierSwiftStateType(BridgeParameter param) => param.Kind switch
    {
        BridgeParameterKind.Primitive when param.SwiftConversion == "!= 0" => "Bool",
        BridgeParameterKind.Primitive => param.SwiftAbiType,
        BridgeParameterKind.String => "String",
        BridgeParameterKind.BoundEnum => param.BridgeTypeName!,
        _ => param.SwiftAbiType,
    };

    /// <summary>
    /// Merges bridge parameter args with synthesized init args in constructor parameter order.
    /// When synthesizedArgs is null/empty, returns viewInitArgs directly (backward compatible).
    /// </summary>
    internal static List<string> BuildMergedInitArgs(
        MethodDecl? constructor,
        List<BridgeParameter> bridgeParams,
        List<string> viewInitArgs,
        List<SynthesizedInitArg>? synthesizedArgs)
    {
        if (synthesizedArgs == null || synthesizedArgs.Count == 0)
            return viewInitArgs;

        if (constructor == null)
            return viewInitArgs;

        var merged = new List<string>();
        var synthDict = synthesizedArgs.ToDictionary(s => s.ParamName, s => s.SwiftExpression);
        var bridgeArgIndex = 0;

        // Iterate constructor params in order (skip [0] return type)
        for (int i = 1; i < constructor.CSSignature.Count; i++)
        {
            var paramName = constructor.CSSignature[i].Name;

            if (synthDict.TryGetValue(paramName, out var synthExpr))
            {
                // Synthesized arg — use expression verbatim
                merged.Add($"{paramName}: {synthExpr}");
            }
            else if (bridgeArgIndex < viewInitArgs.Count)
            {
                // Bridged arg
                merged.Add(viewInitArgs[bridgeArgIndex]);
                bridgeArgIndex++;
            }
        }

        return merged;
    }

    /// <summary>
    /// Builds the Swift closure expression for a typed closure view init argument.
    /// Generates: paramName: { (arg0: SwiftType, ...) [-> ReturnType] in callbackExpr }
    /// </summary>
    private static string BuildTypedClosureViewInitArg(BridgeParameter param)
    {
        var closureArgs = param.ClosureArguments!;
        var closureReturn = param.ClosureReturn;

        // Build closure parameter declarations: (arg0: Int, arg1: Bool, arg2: String)
        var swiftArgDecls = closureArgs.Select((a, i) =>
            $"arg{i}: {GetSwiftTypeFromAbi(a)}").ToList();
        var argDeclStr = string.Join(", ", swiftArgDecls);

        // Check if we have String or class args/returns that need special encoding
        var hasStringArgs = closureArgs.Any(a => a.Kind == BridgeParameterKind.String);
        var hasClassArgs = closureArgs.Any(a => a.Kind == BridgeParameterKind.BoundType);
        var hasNonPrimitiveReturn = closureReturn?.Kind is BridgeParameterKind.String or BridgeParameterKind.BoundType;

        if (hasStringArgs || hasClassArgs || hasNonPrimitiveReturn)
        {
            return BuildComplexClosureViewInitArg(param, closureArgs, closureReturn, argDeclStr);
        }

        // Build callback invocation args: convert Swift types to ABI types
        var callbackArgs = closureArgs.Select((a, i) =>
            a.CSharpConversion != null ? $"arg{i} {a.CSharpConversion}" : $"arg{i}").ToList();
        callbackArgs.Add($"ud_{param.Name}");
        var callbackArgStr = string.Join(", ", callbackArgs);

        if (closureReturn == null)
        {
            // (args...) -> Void
            return $"{param.Name}: {{ ({argDeclStr}) in\n" +
                   $"            cb_{param.Name}?({callbackArgStr})\n" +
                   $"        }}";
        }
        else
        {
            // (args...) -> ReturnType
            var swiftReturnType = GetSwiftTypeFromAbi(closureReturn);
            var defaultVal = closureReturn.SwiftAbiType is "Double" or "Float" ? "0.0" : "0";
            var callExpr = $"cb_{param.Name}?({callbackArgStr}) ?? {defaultVal}";

            if (closureReturn.SwiftConversion != null)
                callExpr = $"({callExpr}) {closureReturn.SwiftConversion}";

            return $"{param.Name}: {{ ({argDeclStr}) -> {swiftReturnType} in\n" +
                   $"            {callExpr}\n" +
                   $"        }}";
        }
    }

    /// <summary>
    /// Builds Swift closure body for closures with String or class arguments.
    /// String args are UTF-8 encoded via withUnsafeBufferPointer.
    /// Class args are passed as opaque pointers via Unmanaged.passRetained.
    /// </summary>
    private static string BuildComplexClosureViewInitArg(
        BridgeParameter param, List<BridgeParameter> closureArgs,
        BridgeParameter? closureReturn, string argDeclStr)
    {
        var sb = new StringBuilder();
        var hasReturn = closureReturn != null;

        // Closure signature: with or without return type annotation
        if (hasReturn)
        {
            var swiftReturnType = GetSwiftTypeFromAbi(closureReturn!);
            sb.Append($"{param.Name}: {{ ({argDeclStr}) -> {swiftReturnType} in\n");
        }
        else
        {
            sb.Append($"{param.Name}: {{ ({argDeclStr}) in\n");
        }

        // Collect String args that need withUnsafeBufferPointer nesting
        var stringArgIndices = new List<int>();
        for (int i = 0; i < closureArgs.Count; i++)
        {
            if (closureArgs[i].Kind == BridgeParameterKind.String)
            {
                sb.Append($"            let arg{i}Bytes = Array(arg{i}.utf8)\n");
                stringArgIndices.Add(i);
            }
        }

        // Open nested withUnsafeBufferPointer blocks for each String arg
        // When the closure has a non-void return, each withUnsafeBufferPointer call must
        // be preceded by `return` so the typed result propagates through all nesting levels.
        var baseIndent = "            ";
        var currentIndent = baseIndent;
        for (int s = 0; s < stringArgIndices.Count; s++)
        {
            var si = stringArgIndices[s];
            var returnPrefix = hasReturn ? "return " : "";
            sb.Append($"{currentIndent}{returnPrefix}arg{si}Bytes.withUnsafeBufferPointer {{ buf{si} in\n");
            currentIndent += "    ";
        }

        // Build callback args: String→(baseAddress, count), Class→Unmanaged, Primitive→direct
        var callbackArgs = new List<string>();
        for (int i = 0; i < closureArgs.Count; i++)
        {
            var a = closureArgs[i];
            if (a.Kind == BridgeParameterKind.String)
            {
                callbackArgs.Add($"buf{i}.baseAddress");
                callbackArgs.Add($"Int(buf{i}.count)");
            }
            else if (a.Kind == BridgeParameterKind.BoundType)
            {
                callbackArgs.Add($"Unmanaged.passRetained(arg{i}).toOpaque()");
            }
            else if (a.CSharpConversion != null)
            {
                callbackArgs.Add($"arg{i} {a.CSharpConversion}");
            }
            else
            {
                callbackArgs.Add($"arg{i}");
            }
        }
        // String-returning closures: add retLen out-parameter before userData
        if (closureReturn?.Kind == BridgeParameterKind.String)
            callbackArgs.Add("lenPtr");
        callbackArgs.Add($"ud_{param.Name}");
        var callbackArgStr = string.Join(", ", callbackArgs);

        if (hasReturn)
        {
            var isStringReturn = closureReturn!.Kind == BridgeParameterKind.String;
            var isClassReturn = closureReturn.Kind == BridgeParameterKind.BoundType;

            if (isStringReturn)
            {
                // String return: decode UTF-8 buffer returned from C# callback
                sb.Append($"{currentIndent}var retLen: Int = 0\n");
                sb.Append($"{currentIndent}let retPtr = withUnsafeMutablePointer(to: &retLen) {{ lenPtr in\n");
                sb.Append($"{currentIndent}    cb_{param.Name}?({callbackArgStr})\n");
                sb.Append($"{currentIndent}}}\n");
                sb.Append($"{currentIndent}defer {{ retPtr?.deallocate() }}\n");
                sb.Append($"{currentIndent}guard let retBuf = retPtr, retLen > 0 else {{ return \"\" }}\n");
                sb.Append($"{currentIndent}return String(bytes: UnsafeBufferPointer(start: retBuf, count: retLen), encoding: .utf8) ?? \"\"\n");
            }
            else if (isClassReturn)
            {
                // Class return: unwrap Unmanaged pointer with ownership transfer
                var callExpr = $"cb_{param.Name}?({callbackArgStr})";
                sb.Append($"{currentIndent}guard let retPtr = {callExpr} else {{\n");
                sb.Append($"{currentIndent}    fatalError(\"SBW: closure returned null for non-optional class return\")\n");
                sb.Append($"{currentIndent}}}\n");
                sb.Append($"{currentIndent}return Unmanaged<{closureReturn.BridgeTypeName}>.fromOpaque(retPtr).takeRetainedValue()\n");
            }
            else
            {
                // Primitive return: default value + optional chaining + conversion
                var defaultVal = closureReturn.SwiftAbiType is "Double" or "Float" ? "0.0" : "0";
                var callExpr = $"cb_{param.Name}?({callbackArgStr}) ?? {defaultVal}";
                if (closureReturn.SwiftConversion != null)
                    callExpr = $"({callExpr}) {closureReturn.SwiftConversion}";

                // String args require `return` keyword inside withUnsafeBufferPointer blocks
                if (stringArgIndices.Count > 0)
                    sb.Append($"{currentIndent}return {callExpr}\n");
                else
                    sb.Append($"{currentIndent}{callExpr}\n");
            }
        }
        else
        {
            sb.Append($"{currentIndent}cb_{param.Name}?({callbackArgStr})\n");
        }

        // Close nested withUnsafeBufferPointer blocks — inner blocks need `return` propagation
        for (int s = stringArgIndices.Count - 1; s >= 0; s--)
        {
            currentIndent = baseIndent + new string(' ', 4 * s);
            sb.Append($"{currentIndent}}}\n");
        }

        sb.Append($"        }}");
        return sb.ToString();
    }

    /// <summary>
    /// Maps an ABI BridgeParameter back to its Swift type name for closure signatures.
    /// e.g., Int32 with SwiftConversion "!= 0" → Bool; Int → Int; Double → Double
    /// </summary>
    private static string GetSwiftTypeFromAbi(BridgeParameter param)
    {
        if (param.SwiftConversion == "!= 0") return "Bool";
        if (param.Kind == BridgeParameterKind.String) return "String";
        if (param.Kind == BridgeParameterKind.BoundType) return param.BridgeTypeName!;
        return param.SwiftAbiType;
    }

    /// <summary>
    /// Emits a typed closure [UnmanagedCallersOnly] trampoline that unpacks GCHandle → delegate,
    /// converts ABI args to C# types, calls the delegate, and converts the return value back.
    /// </summary>
    private static void EmitTypedClosureTrampoline(StringBuilder sb, BridgeParameter param)
    {
        var trampolineName = char.ToUpperInvariant(param.Name[0]) + param.Name[1..] + "Trampoline";
        var closureArgs = param.ClosureArguments!;
        var closureReturn = param.ClosureReturn;

        // Build trampoline parameters: String args expand to (IntPtr ptr, nint len)
        var trampolineParams = new List<string>();
        foreach (var (a, i) in closureArgs.Select((a, i) => (a, i)))
        {
            if (a.Kind == BridgeParameterKind.String)
            {
                trampolineParams.Add($"IntPtr arg{i}Ptr");
                trampolineParams.Add($"nint arg{i}Len");
            }
            else
            {
                trampolineParams.Add($"{a.CSharpPInvokeType} arg{i}");
            }
        }
        // String-returning closures: add retLen out-parameter before userData
        if (closureReturn?.Kind == BridgeParameterKind.String)
            trampolineParams.Add("IntPtr retLenPtr");
        trampolineParams.Add("IntPtr userData");
        var returnType = closureReturn?.CSharpPInvokeType ?? "void";

        sb.AppendLine($"        [UnmanagedCallersOnly(CallConvs = new[] {{ typeof(global::System.Runtime.CompilerServices.CallConvCdecl) }})]");
        sb.AppendLine($"        private static {returnType} {trampolineName}({string.Join(", ", trampolineParams)})");
        sb.AppendLine("        {");
        sb.AppendLine("            if (userData != IntPtr.Zero)");
        sb.AppendLine("            {");
        sb.AppendLine("                var h = GCHandle.FromIntPtr(userData);");

        // Build C# delegate type for the cast
        var delegateType = GetCSharpDelegateType(closureArgs, closureReturn);

        var hasStringOrClassArgs = closureArgs.Any(a => a.Kind is BridgeParameterKind.String or BridgeParameterKind.BoundType);

        if (hasStringOrClassArgs)
        {
            // String/class args need decoding before delegate invocation
            foreach (var (a, i) in closureArgs.Select((a, i) => (a, i)))
            {
                if (a.Kind == BridgeParameterKind.String)
                {
                    sb.AppendLine($"                var str{i} = \"\";");
                    sb.AppendLine($"                if (arg{i}Ptr != IntPtr.Zero && arg{i}Len > 0)");
                    sb.AppendLine($"                    unsafe {{ str{i} = Encoding.UTF8.GetString((byte*)arg{i}Ptr, (int)arg{i}Len); }}");
                }
                else if (a.Kind == BridgeParameterKind.BoundType)
                {
                    sb.AppendLine($"                var arg{i}Obj = ({a.CSharpTypeName})Swift.Runtime.InteropServices.SwiftMarshal.MarshalFromSwift<{a.CSharpTypeName}>(arg{i});");
                }
            }

            // Build delegate args using decoded values
            var delegateArgs = new List<string>();
            for (int i = 0; i < closureArgs.Count; i++)
            {
                var a = closureArgs[i];
                if (a.Kind == BridgeParameterKind.String)
                    delegateArgs.Add($"str{i}");
                else if (a.Kind == BridgeParameterKind.BoundType)
                    delegateArgs.Add($"arg{i}Obj");
                else if (a.SwiftConversion != null)
                    delegateArgs.Add($"arg{i} {a.SwiftConversion}");
                else
                    delegateArgs.Add($"arg{i}");
            }
            var delegateArgStr = string.Join(", ", delegateArgs);

            if (closureReturn == null)
            {
                sb.AppendLine($"                if (h.Target is {delegateType} action)");
                sb.AppendLine($"                    action({delegateArgStr});");
            }
            else
            {
                sb.AppendLine($"                if (h.Target is {delegateType} func)");
                sb.AppendLine("                {");
                sb.AppendLine($"                    var result = func({delegateArgStr});");
                EmitTrampolineReturnEncoding(sb, closureReturn);
                sb.AppendLine("                }");
            }
        }
        else
        {
            // Simple primitive args — direct pass
            var delegateArgs = closureArgs.Select((a, i) =>
                a.SwiftConversion != null ? $"arg{i} {a.SwiftConversion}" : $"arg{i}").ToList();
            var delegateArgStr = string.Join(", ", delegateArgs);

            if (closureReturn == null)
            {
                sb.AppendLine($"                if (h.Target is {delegateType} action)");
                sb.AppendLine($"                    action({delegateArgStr});");
            }
            else
            {
                sb.AppendLine($"                if (h.Target is {delegateType} func)");
                sb.AppendLine("                {");
                sb.AppendLine($"                    var result = func({delegateArgStr});");
                EmitTrampolineReturnEncoding(sb, closureReturn);
                sb.AppendLine("                }");
            }
        }

        sb.AppendLine("            }");
        if (closureReturn != null)
        {
            var defaultReturn = closureReturn.Kind is BridgeParameterKind.String or BridgeParameterKind.BoundType
                ? "IntPtr.Zero" : "0";
            sb.AppendLine($"            return {defaultReturn};");
        }
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    /// <summary>
    /// Emits the return encoding for a typed closure trampoline based on return type kind.
    /// String return: allocates native buffer, encodes UTF-8. Class return: retains + returns pointer.
    /// </summary>
    private static void EmitTrampolineReturnEncoding(StringBuilder sb, BridgeParameter closureReturn)
    {
        if (closureReturn.Kind == BridgeParameterKind.String)
        {
            // String return: encode to native UTF-8 buffer, write length to out-parameter
            sb.AppendLine("                    var bytes = Encoding.UTF8.GetBytes(result ?? \"\");");
            sb.AppendLine("                    if (bytes.Length > 0)");
            sb.AppendLine("                    {");
            sb.AppendLine("                        unsafe");
            sb.AppendLine("                        {");
            sb.AppendLine("                            var nativePtr = (byte*)NativeMemory.Alloc((nuint)bytes.Length);");
            sb.AppendLine("                            bytes.CopyTo(new Span<byte>(nativePtr, bytes.Length));");
            sb.AppendLine("                            *(nint*)retLenPtr = bytes.Length;");
            sb.AppendLine("                            return (IntPtr)nativePtr;");
            sb.AppendLine("                        }");
            sb.AppendLine("                    }");
            sb.AppendLine("                    unsafe { *(nint*)retLenPtr = 0; }");
            sb.AppendLine("                    return IntPtr.Zero;");
        }
        else if (closureReturn.Kind == BridgeParameterKind.BoundType)
        {
            // Class return: retain the Swift object and return its pointer
            sb.AppendLine("                    if (result != null)");
            sb.AppendLine("                    {");
            sb.AppendLine("                        var ptr = result.Payload.DangerousGetHandle();");
            sb.AppendLine("                        Swift.Runtime.Arc.Retain(ptr);");
            sb.AppendLine("                        return ptr;");
            sb.AppendLine("                    }");
            sb.AppendLine("                    return IntPtr.Zero;");
        }
        else if (closureReturn.CSharpConversion != null)
        {
            sb.AppendLine($"                    return result {closureReturn.CSharpConversion};");
        }
        else
        {
            sb.AppendLine($"                    return result;");
        }
    }

    /// <summary>
    /// Gets the C# delegate type for a typed closure (e.g., Action&lt;nint, bool&gt; or Func&lt;nint, bool&gt;).
    /// </summary>
    private static string GetCSharpDelegateType(List<BridgeParameter> closureArgs, BridgeParameter? closureReturn)
    {
        var argTypes = closureArgs.Select(GetClosureArgCSharpType).ToList();

        if (closureReturn == null)
        {
            return argTypes.Count == 0 ? "Action" : $"Action<{string.Join(", ", argTypes)}>";
        }
        else
        {
            var returnType = GetFactoryParamType(closureReturn);
            argTypes.Add(returnType);
            return $"Func<{string.Join(", ", argTypes)}>";
        }
    }

    /// <summary>
    /// Gets the idiomatic C# type for a closure argument used in delegate types.
    /// String → "string", BoundType → fully-qualified class name, others → same as factory param.
    /// </summary>
    private static string GetClosureArgCSharpType(BridgeParameter param) => param.Kind switch
    {
        BridgeParameterKind.String => "string",
        BridgeParameterKind.BoundType or BridgeParameterKind.BoundStruct => param.CSharpTypeName!,
        _ => GetFactoryParamType(param),
    };

    /// <summary>
    /// Gets the C# factory parameter type for a typed closure (e.g., Action&lt;nint&gt;? or Func&lt;nint, bool&gt;?).
    /// </summary>
    private static string GetTypedClosureFactoryType(BridgeParameter param)
    {
        var closureArgs = param.ClosureArguments!;
        var closureReturn = param.ClosureReturn;
        return GetCSharpDelegateType(closureArgs, closureReturn) + "?";
    }

    /// <summary>
    /// Gets the delegate* unmanaged function pointer type for a closure parameter.
    /// VoidClosure: delegate* unmanaged[Cdecl]&lt;IntPtr, void&gt;
    /// TypedClosure: delegate* unmanaged[Cdecl]&lt;argTypes..., IntPtr, returnType&gt;
    /// </summary>
    private static string GetClosureFunctionPointerType(BridgeParameter param)
    {
        if (param.Kind == BridgeParameterKind.VoidClosure)
            return "delegate* unmanaged[Cdecl]<IntPtr, void>";

        var closureArgs = param.ClosureArguments!;
        var closureReturn = param.ClosureReturn;
        var fnPtrTypes = new List<string>();
        foreach (var a in closureArgs)
        {
            if (a.Kind == BridgeParameterKind.String)
            {
                fnPtrTypes.Add("IntPtr"); // ptr
                fnPtrTypes.Add("nint");   // len
            }
            else
            {
                fnPtrTypes.Add(a.CSharpPInvokeType);
            }
        }
        // String-returning closures: add retLen out-parameter before userData
        if (closureReturn?.Kind == BridgeParameterKind.String)
            fnPtrTypes.Add("IntPtr"); // retLenPtr
        fnPtrTypes.Add("IntPtr"); // userData
        fnPtrTypes.Add(closureReturn?.CSharpPInvokeType ?? "void"); // return type
        return $"delegate* unmanaged[Cdecl]<{string.Join(", ", fnPtrTypes)}>";
    }

    private static string GetInitDescription(ViewBridgeInfo info)
    {
        if (info.Constructors.Count == 0)
            return "init()";

        var ctor = info.Constructors[0];
        var paramDescs = new List<string>();
        for (int i = 1; i < ctor.CSSignature.Count; i++)
        {
            var param = ctor.CSSignature[i];
            paramDescs.Add($"{param.Name}: {param.SwiftTypeSpec}");
        }

        return paramDescs.Count == 0 ? "init()" : $"init({string.Join(", ", paramDescs)})";
    }

    private static string GetInitParamSummary(ViewBridgeInfo info)
    {
        if (info.UnsupportedReason != null)
            return info.UnsupportedReason;

        if (info.Constructors.Count == 0)
            return "no parameters";

        var ctor = info.Constructors[0];
        var paramDescs = new List<string>();
        for (int i = 1; i < ctor.CSSignature.Count; i++)
        {
            var param = ctor.CSSignature[i];
            paramDescs.Add($"{param.Name}: {param.SwiftTypeSpec}");
        }

        return paramDescs.Count == 0 ? "no parameters" : string.Join(", ", paramDescs);
    }

