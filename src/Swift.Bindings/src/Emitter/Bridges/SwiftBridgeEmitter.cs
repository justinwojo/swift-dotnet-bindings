using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace BindingsGeneration;

/// <summary>One architecture's bridge assembly: the source, the bridges it defines and the plans it could not emit.</summary>
public sealed record SwiftBridgeAssembly(
    SwiftArchitecture Architecture,
    string Source,
    ImmutableArray<string> Bridges,
    ImmutableArray<SwiftBridgeRefusal> Refused);

/// <summary>A plan the emitter did not turn into assembly, and why.</summary>
public sealed record SwiftBridgeRefusal(string Symbol, string Reason);

/// <summary>
/// Turns forward plans (<see cref="SwiftCallPlan"/>) into the native bridges they describe, one
/// assembly file per architecture. The emitter is mechanical: every instruction follows from the
/// plan's native half (where each argument arrives, the stack prefix, the special-register moves,
/// the result plan and the frame); it decides nothing the plan does not say, and refuses a plan
/// whose shape it has no template for.
/// </summary>
/// <remarks>
/// <para>
/// Each bridge has one frame shape: a frame record (<c>x29</c>/<c>x30</c>, or <c>rbp</c>) whose
/// CFA is the frame pointer plus 16, the plan's saved registers immediately below it in the order
/// the compact unwind format reads them, then the plan's locals, with <c>sp</c> 16-aligned at the
/// call. The CFI describes exactly that frame, so the assembler's compact encoding and any DWARF
/// row agree with the code; the unwind validator checks both against the instructions.
/// </para>
/// <para>
/// Every external symbol is weak: a bridge whose target is absent on the running OS must not stop
/// its image from loading (the caller checks availability before calling).
/// </para>
/// </remarks>
public static class SwiftBridgeEmitter
{
    /// <summary>The bridges' largest local area: one <c>sub sp</c> immediate.</summary>
    public const int MaximumLocalBytes = 4080;

    private static readonly Regex SymbolPattern = new(@"^[A-Za-z_$][A-Za-z0-9_$.]*$", RegexOptions.Compiled | RegexOptions.CultureInvariant);

    /// <summary>Emits every plan it can, sorted by symbol, into one assembly file for <paramref name="architecture"/>.</summary>
    public static SwiftBridgeAssembly Emit(IEnumerable<SwiftCallPlan> plans, SwiftArchitecture architecture)
    {
        var ordered = plans.GroupBy(p => p.Symbol, StringComparer.Ordinal).Select(g => g.First())
            .OrderBy(p => p.Symbol, StringComparer.Ordinal).ToList();
        var bodies = new StringBuilder();
        var emitted = ImmutableArray.CreateBuilder<string>();
        var refused = ImmutableArray.CreateBuilder<SwiftBridgeRefusal>();
        var weak = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var plan in ordered)
        {
            if (Refusal(plan, architecture) is { } why)
            {
                refused.Add(new SwiftBridgeRefusal(plan.Symbol, why));
                continue;
            }
            var native = plan.Body.Architectures.Single(a => a.Architecture == architecture);
            bodies.Append(architecture == SwiftArchitecture.Arm64 ? Arm64(plan, native) : X86_64(plan, native));
            emitted.Add(plan.Symbol);
            if (plan.Body.Target is { } target)
                weak.Add(target);
        }

        var source = new StringBuilder();
        source.Append("/* Generated by Swift.Bindings from Swift call plans: one bridge per plan, named by its hash. Do not edit. */\n");
        source.Append(".section __TEXT,__text,regular,pure_instructions\n");
        foreach (var symbol in weak)
            source.Append(".weak_reference _").Append(symbol).Append('\n');
        source.Append(bodies);
        source.Append(".subsections_via_symbols\n");
        return new SwiftBridgeAssembly(architecture, source.ToString(), emitted.ToImmutable(), refused.ToImmutable());
    }

    /// <summary>Why <paramref name="plan"/> has no bridge on <paramref name="architecture"/>, or null when it can be emitted.</summary>
    public static string? Refusal(SwiftCallPlan plan, SwiftArchitecture architecture)
    {
        if (architecture is not (SwiftArchitecture.Arm64 or SwiftArchitecture.X86_64))
            return $"no bridge template for {architecture}";
        if (plan.Body.Kind == SwiftPlanKind.Reverse)
            return "reverse stubs have no template yet";
        if (plan.Body.Kind == SwiftPlanKind.Forward && (plan.Body.Target is not { } target || !SymbolPattern.IsMatch(target)))
            return $"the target '{plan.Body.Target}' is not a symbol the assembler can name";
        if (!SymbolPattern.IsMatch(plan.Symbol))
            return $"the bridge name '{plan.Symbol}' is not a symbol the assembler can name";
        var native = plan.Body.Architectures.SingleOrDefault(a => a.Architecture == architecture);
        if (native is null)
            return $"the plan has no {architecture} half";
        var convention = SwiftCallingConvention.For(architecture);
        var frame = native.Frame;
        if (frame.LocalBytes is < 0 or > MaximumLocalBytes || frame.LocalBytes % (architecture == SwiftArchitecture.Arm64 ? 16 : 8) != 0)
            return $"the frame's {frame.LocalBytes} local bytes do not fit the template";
        if (!frame.Locals.IsDefaultOrEmpty)
            return "a forward bridge has no frame locals";
        var expectedHead = architecture == SwiftArchitecture.Arm64 ? new[] { "x29", "x30" } : new[] { "rbp" };
        if (!frame.SavedRegisters.Take(expectedHead.Length).SequenceEqual(expectedHead))
            return "the frame does not begin with the frame record";
        if (architecture == SwiftArchitecture.Arm64 && frame.SavedRegisters.Length % 2 != 0)
            return "arm64 saved registers come in pairs";
        foreach (var register in frame.SavedRegisters.Skip(expectedHead.Length))
            if (!CalleeSaved(architecture).Contains(register))
                return $"the frame saves {register}, which is not callee-saved";
        foreach (var operand in native.Outgoing.Where(o => o.Kind == SwiftOperandKind.Stack))
        {
            if (operand.Size is not (1 or 2 or 4 or 8) || operand.Offset < 0 || operand.Offset + operand.Size > frame.OutgoingStackBytes)
                return $"the stack argument {operand} is outside the outgoing area";
            if (operand.Offset % operand.Size != 0)
                return $"the stack argument {operand} is not naturally aligned";
        }
        for (int i = 0; i < native.Outgoing.Length; i++)
            if (i >= native.Incoming.Length || native.Incoming[i] != native.Outgoing[i])
                return $"argument {i} does not arrive where the callee reads it";
        foreach (var move in native.Moves)
        {
            if (move.To.Kind != SwiftOperandKind.Register || move.From.Kind is not (SwiftOperandKind.Register or SwiftOperandKind.Stack) || move.From.Size != 8)
                return $"the move {move.From} -> {move.To} has no template";
        }
        if (native.ZeroError != (frame.ErrorSlot is not null))
            return "a forward bridge zeroes the error register exactly when it stores it";
        if (!native.AfterCall.IsDefaultOrEmpty)
            return "a forward bridge makes no moves after the call";
        switch (native.Result.Kind)
        {
            case SwiftResultKind.Scalar when native.Result.Register is not { Kind: SwiftOperandKind.Register, Register: { } register }
                || (register != convention.ScalarResult(SwiftRegisterClass.General) && register != convention.ScalarResult(SwiftRegisterClass.Float)):
                return "a scalar result stays in the first result register";
            case SwiftResultKind.Direct when frame.ResultBuffer is null:
                return "a direct result needs the result buffer register";
            case SwiftResultKind.Direct:
                foreach (var piece in native.Result.Moves)
                {
                    if (piece.Size is not (1 or 2 or 4 or 8) || piece.BufferOffset < 0 || piece.Register.Register is null)
                        return $"the result piece {piece.Register} at {piece.BufferOffset} has no template";
                    if (architecture == SwiftArchitecture.Arm64 && piece.BufferOffset % piece.Size != 0 && piece.BufferOffset > 255)
                        return $"the result piece at {piece.BufferOffset} is neither aligned nor in reach";
                }
                break;
        }
        if (native.Result.ExtendTo32 is { } extension && (extension is not ("sign" or "zero") || native.Result.Register?.Size is not (1 or 2)))
            return $"the result extension '{extension}' has no template";
        return null;
    }

    private static IReadOnlySet<string> CalleeSaved(SwiftArchitecture architecture) => architecture == SwiftArchitecture.Arm64
        ? new HashSet<string>(StringComparer.Ordinal) { "x19", "x20", "x21", "x22", "x23", "x24", "x25", "x26", "x27", "x28" }
        : new HashSet<string>(StringComparer.Ordinal) { "rbx", "r12", "r13", "r14", "r15" };

    private static string Hex(int value) => value.ToString(CultureInfo.InvariantCulture);

    // ---- arm64 ----

    private static string Arm64(SwiftCallPlan plan, SwiftNativePlan native)
    {
        var frame = native.Frame;
        var s = new StringBuilder();
        s.Append(".globl _").Append(plan.Symbol).Append('\n');
        s.Append(".p2align 2\n");
        s.Append('_').Append(plan.Symbol).Append(":\n");
        s.Append("  .cfi_startproc\n");
        s.Append("  stp x29, x30, [sp, #-16]!\n");
        s.Append("  mov x29, sp\n");
        s.Append("  .cfi_def_cfa w29, 16\n");
        s.Append("  .cfi_offset w30, -8\n");
        s.Append("  .cfi_offset w29, -16\n");
        var pairs = new List<(string First, string Second)>();
        for (int i = 2; i < frame.SavedRegisters.Length; i += 2)
            pairs.Add((frame.SavedRegisters[i], frame.SavedRegisters[i + 1]));
        foreach (var (first, second) in pairs)
            s.Append("  stp ").Append(first).Append(", ").Append(second).Append(", [sp, #-16]!\n");
        // Pair j (from 1) sits at CFA - 16(j+1): its first register at the lower address. The
        // compact format reads the pairs from the frame record down, the second register first.
        for (int j = 0; j < pairs.Count; j++)
        {
            int baseOffset = 16 * (j + 2);
            s.Append("  .cfi_offset w").Append(pairs[j].Second[1..]).Append(", -").Append(Hex(baseOffset - 8)).Append('\n');
            s.Append("  .cfi_offset w").Append(pairs[j].First[1..]).Append(", -").Append(Hex(baseOffset)).Append('\n');
        }
        if (frame.LocalBytes > 0)
            s.Append("  sub sp, sp, #").Append(Hex(frame.LocalBytes)).Append('\n');

        // The stack prefix: the caller's argument area is at fp + 16.
        foreach (var operand in native.Outgoing.Where(o => o.Kind == SwiftOperandKind.Stack))
        {
            var (load, store, register) = Arm64Sized(operand.Size, "9");
            s.Append("  ").Append(load).Append(' ').Append(register).Append(", [x29, #").Append(Hex(16 + operand.Offset)).Append("]\n");
            s.Append("  ").Append(store).Append(' ').Append(register).Append(", [sp, #").Append(Hex(operand.Offset)).Append("]\n");
        }
        foreach (var move in native.Moves)
        {
            if (move.From.Kind == SwiftOperandKind.Register)
                s.Append("  mov ").Append(move.To.Register).Append(", ").Append(move.From.Register).Append('\n');
            else
                s.Append("  ldr ").Append(move.To.Register).Append(", [x29, #").Append(Hex(16 + move.From.Offset)).Append("]\n");
        }
        if (native.ZeroError)
            s.Append("  mov x21, #0\n");
        if (plan.Body.Kind == SwiftPlanKind.ForwardThick)
            s.Append("  blr x16\n");
        else
            s.Append("  bl _").Append(plan.Body.Target).Append('\n');
        if (frame.ErrorSlot is { } errorSlot)
            s.Append("  str x21, [").Append(errorSlot).Append("]\n");
        switch (native.Result.Kind)
        {
            case SwiftResultKind.Scalar when native.Result.ExtendTo32 is { } extension:
            {
                var op = (extension, native.Result.Register!.Size) switch
                {
                    ("sign", 1) => "sxtb",
                    ("zero", 1) => "uxtb",
                    ("sign", _) => "sxth",
                    _ => "uxth",
                };
                s.Append("  ").Append(op).Append(" w0, w0\n");
                break;
            }
            case SwiftResultKind.Direct:
                foreach (var piece in native.Result.Moves)
                {
                    var name = piece.Register.Register!;
                    bool isFloat = name.StartsWith('v');
                    var register = isFloat
                        ? (piece.Size == 8 ? "d" : piece.Size == 4 ? "s" : piece.Size == 2 ? "h" : "b") + name[1..]
                        : (piece.Size == 8 ? "x" : "w") + name[1..];
                    var store = isFloat || piece.Size >= 4 ? "str" : piece.Size == 2 ? "strh" : "strb";
                    if (piece.BufferOffset % piece.Size != 0)
                        store = store.Replace("str", "stur");
                    s.Append("  ").Append(store).Append(' ').Append(register).Append(", [").Append(frame.ResultBuffer)
                        .Append(", #").Append(Hex(piece.BufferOffset)).Append("]\n");
                }
                break;
        }
        if (frame.LocalBytes > 0)
            s.Append("  add sp, sp, #").Append(Hex(frame.LocalBytes)).Append('\n');
        for (int j = pairs.Count - 1; j >= 0; j--)
            s.Append("  ldp ").Append(pairs[j].First).Append(", ").Append(pairs[j].Second).Append(", [sp], #16\n");
        s.Append("  ldp x29, x30, [sp], #16\n");
        s.Append("  ret\n");
        s.Append("  .cfi_endproc\n");
        return s.ToString();
    }

    private static (string Load, string Store, string Register) Arm64Sized(int size, string number) => size switch
    {
        8 => ("ldr", "str", "x" + number),
        4 => ("ldr", "str", "w" + number),
        2 => ("ldrh", "strh", "w" + number),
        _ => ("ldrb", "strb", "w" + number),
    };

    // ---- x86_64 ----

    private static string X86_64(SwiftCallPlan plan, SwiftNativePlan native)
    {
        var frame = native.Frame;
        var saved = frame.SavedRegisters.Skip(1).ToList();
        var s = new StringBuilder();
        s.Append(".globl _").Append(plan.Symbol).Append('\n');
        s.Append(".p2align 4, 0x90\n");
        s.Append('_').Append(plan.Symbol).Append(":\n");
        s.Append("  .cfi_startproc\n");
        s.Append("  pushq %rbp\n");
        s.Append("  .cfi_def_cfa_offset 16\n");
        s.Append("  .cfi_offset %rbp, -16\n");
        s.Append("  movq %rsp, %rbp\n");
        s.Append("  .cfi_def_cfa_register %rbp\n");
        foreach (var register in saved)
            s.Append("  pushq %").Append(register).Append('\n');
        // The k-th push (from 1) is at CFA - 16 - 8k. The compact format reads the saved registers
        // from the lowest address up, in the order the CFI names them: the last push first.
        for (int k = saved.Count; k >= 1; k--)
            s.Append("  .cfi_offset %").Append(saved[k - 1]).Append(", -").Append(Hex(16 + 8 * k)).Append('\n');
        if (frame.LocalBytes > 0)
            s.Append("  subq $").Append(Hex(frame.LocalBytes)).Append(", %rsp\n");

        // The stack prefix, in eight-byte slots: the caller's argument area is at rbp + 16.
        foreach (var operand in native.Outgoing.Where(o => o.Kind == SwiftOperandKind.Stack))
        {
            s.Append("  movq ").Append(Hex(16 + operand.Offset)).Append("(%rbp), %r10\n");
            s.Append("  movq %r10, ").Append(Hex(operand.Offset)).Append("(%rsp)\n");
        }
        foreach (var move in native.Moves)
        {
            if (move.From.Kind == SwiftOperandKind.Register)
                s.Append("  movq %").Append(move.From.Register).Append(", %").Append(move.To.Register).Append('\n');
            else
                s.Append("  movq ").Append(Hex(16 + move.From.Offset)).Append("(%rbp), %").Append(move.To.Register).Append('\n');
        }
        if (native.ZeroError)
            s.Append("  xorl %r12d, %r12d\n");
        if (plan.Body.Kind == SwiftPlanKind.ForwardThick)
            s.Append("  callq *%r11\n");
        else
            s.Append("  callq _").Append(plan.Body.Target).Append('\n');
        if (frame.ErrorSlot is { } errorSlot)
            s.Append("  movq %r12, (%").Append(errorSlot).Append(")\n");
        switch (native.Result.Kind)
        {
            case SwiftResultKind.Scalar when native.Result.ExtendTo32 is { } extension:
            {
                var op = (extension, native.Result.Register!.Size) switch
                {
                    ("sign", 1) => "movsbl %al, %eax",
                    ("zero", 1) => "movzbl %al, %eax",
                    ("sign", _) => "movswl %ax, %eax",
                    _ => "movzwl %ax, %eax",
                };
                s.Append("  ").Append(op).Append('\n');
                break;
            }
            case SwiftResultKind.Direct:
                foreach (var piece in native.Result.Moves)
                {
                    var name = piece.Register.Register!;
                    string instruction = name.StartsWith("xmm", StringComparison.Ordinal)
                        ? (piece.Size == 8 ? "movsd %" : "movss %") + name
                        : piece.Size switch
                        {
                            8 => "movq %" + name,
                            4 => "movl %" + X86Sub(name, 4),
                            2 => "movw %" + X86Sub(name, 2),
                            _ => "movb %" + X86Sub(name, 1),
                        };
                    s.Append("  ").Append(instruction).Append(", ").Append(Hex(piece.BufferOffset)).Append("(%").Append(frame.ResultBuffer).Append(")\n");
                }
                break;
        }
        if (saved.Count > 0)
            s.Append("  leaq -").Append(Hex(8 * saved.Count)).Append("(%rbp), %rsp\n");
        else
            s.Append("  movq %rbp, %rsp\n");
        for (int k = saved.Count - 1; k >= 0; k--)
            s.Append("  popq %").Append(saved[k]).Append('\n');
        s.Append("  popq %rbp\n");
        s.Append("  retq\n");
        s.Append("  .cfi_endproc\n");
        return s.ToString();
    }

    /// <summary>The 4-, 2- or 1-byte name of a 64-bit general register.</summary>
    private static string X86Sub(string register, int size) => (register, size) switch
    {
        ("rax", 4) => "eax", ("rax", 2) => "ax", ("rax", _) => "al",
        ("rdx", 4) => "edx", ("rdx", 2) => "dx", ("rdx", _) => "dl",
        ("rcx", 4) => "ecx", ("rcx", 2) => "cx", ("rcx", _) => "cl",
        ("rbx", 4) => "ebx", ("rbx", 2) => "bx", ("rbx", _) => "bl",
        ("rsi", 4) => "esi", ("rsi", 2) => "si", ("rsi", _) => "sil",
        ("rdi", 4) => "edi", ("rdi", 2) => "di", ("rdi", _) => "dil",
        _ when register.StartsWith('r') && char.IsDigit(register[1]) => register + (size == 4 ? "d" : size == 2 ? "w" : "b"),
        _ => throw new ArgumentOutOfRangeException(nameof(register), register, "not a 64-bit general register"),
    };
}
